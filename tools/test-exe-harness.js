#!/usr/bin/env node
// Actual-EXE integration vectors for EL3LB, EL3TX and EL3RX.
// SPDX-License-Identifier: BSD-3-Clause
'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const {runExe} = require('./exe-harness/harness.js');

const root = path.resolve(__dirname, '..');
const exe = (name) => path.join(root, 'build', `${name}.EXE`);
const cardMac = [0x02, 0x60, 0x8c, 0x12, 0x34, 0x56];
const destMac = [0x02, 0x00, 0x00, 0x00, 0x00, 0x01];
const broadcast = [0xff, 0xff, 0xff, 0xff, 0xff, 0xff];
const foreign = [0x02, 0xaa, 0xbb, 0xcc, 0xdd, 0xee];
let cases = 0;

function checkCleanup(result) {
  assert.deepStrictEqual(result.cleanup, {isaClosed: true, pagesFreed: true, done: true});
  cases++;
}

function expectedFrame(length, pattern, sequence = 0, destination = destMac) {
  const frame = [...destination, ...cardMac, 0x88, 0xb5];
  const constants = {'00': 0x00, 'FF': 0xff, '55': 0x55, 'AA': 0xaa};
  while (frame.length < length) {
    const index = frame.length - 14;
    frame.push(pattern === 'INC' ? (index + sequence) & 0xff : constants[pattern]);
  }
  while (frame.length < 60) frame.push(0);
  return Buffer.from(frame).toString('hex');
}

function rxFrame(destination, sequence, length = 60, type = 0x88b5) {
  const frame = [...destination, ...destMac, type >> 8, type & 0xff];
  while (frame.length < length) frame.push((frame.length - 14 + sequence) & 0xff);
  return frame;
}

function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function run(name, args, scenario = {}) { return runExe(exe(name), args, scenario); }

// Header/load/boundary checks use the binaries that are also placed in IMG.
for (const name of ['EL3LB', 'EL3TX', 'EL3RX']) {
  const image = fs.readFileSync(exe(name));
  assert.strictEqual(image.toString('ascii', 0, 3), 'EXE');
  assert.strictEqual(image.readUInt16LE(4), 128);
  assert.strictEqual(image.readUInt16LE(16), 0x8100);
  assert.ok(0x8080 + image.length <= 0xc000);
  cases++;
}

const loopback = run('EL3LB', '-n 1');
assert.strictEqual(loopback.exitCode, 0);
assert.strictEqual(loopback.transmittedFrames.length, 52);
assert.match(loopback.output, /MATRIX OK=#0028/);
assert.match(loopback.output, /BURST OK=#000C/);
assert.match(loopback.output, /RESULT OK/);
checkCleanup(loopback);

// Stage 5 discovery/activation selection and common DSS exit-code mapping.
for (const slot of [0, 1]) {
  const result = run('EL3LB', `-s ${slot} -n 1`, {slot});
  assert.strictEqual(result.exitCode, 0); assert.strictEqual(result.transmittedFrames.length, 52); checkCleanup(result);
}
for (const base of [0x200, 0x300, 0x3e0]) {
  const result = run('EL3LB', `-b #${base.toString(16).toUpperCase()} -n 1`);
  assert.strictEqual(result.exitCode, 0); assert.strictEqual(result.card.base, base); checkCleanup(result);
}
const loopbackNoCard = run('EL3LB', '-n 1', {cardPresent: false});
assert.strictEqual(loopbackNoCard.exitCode, 2); assert.match(loopbackNoCard.output, /RESULT FAIL code=3/); checkCleanup(loopbackNoCard);
const loopbackBadCli = run('EL3LB', '-n 0');
assert.strictEqual(loopbackBadCli.exitCode, 1); assert.match(loopbackBadCli.output, /RESULT FAIL code=2/); checkCleanup(loopbackBadCli);

// Every required length and pattern is generated by the real EL3TX.EXE.
for (const length of [14, 42, 59, 60, 61, 62, 63, 1514]) {
  for (const pattern of ['00', 'FF', '55', 'AA', 'INC']) {
    const result = run('EL3TX', `-d 02:00:00:00:00:01 -l ${length} -f ${pattern} -w 2`);
    assert.strictEqual(result.exitCode, 0);
    assert.deepStrictEqual(result.transmittedFrames, [expectedFrame(length, pattern)]);
    const record = result.txRecords[0];
    const effective = Math.max(length, 60);
    assert.strictEqual(record.preamble, Buffer.from([effective & 0xff, 0x80 | (effective >> 8), 0, 0]).toString('hex'));
    assert.strictEqual(record.dwordPad, '00'.repeat((-effective) & 3));
    checkCleanup(result);
  }
}

const burst = run('EL3TX', '-d FF:FF:FF:FF:FF:FF -l 61 -f INC -n 10 -w 2');
assert.strictEqual(burst.exitCode, 0);
assert.strictEqual(burst.transmittedFrames.length, 10);
for (let i = 0; i < 10; i++) assert.strictEqual(burst.transmittedFrames[i], expectedFrame(61, 'INC', i, broadcast));
checkCleanup(burst);

// Slot, explicit base, alternate ID port, no-card and CLI boundaries.
for (const slot of [0, 1]) {
  const result = run('EL3TX', `-s ${slot} -d 02:00:00:00:00:01 -w 1`, {slot});
  assert.strictEqual(result.exitCode, 0); checkCleanup(result);
}
for (const base of [0x200, 0x300, 0x3e0]) {
  const value = `#${base.toString(16).toUpperCase()}`;
  const result = run('EL3TX', `-b ${value} -d 02:00:00:00:00:01 -w 1`);
  assert.strictEqual(result.exitCode, 0); assert.strictEqual(result.card.base, base); checkCleanup(result);
}
const altId = run('EL3TX', '-p #100 -d 02:00:00:00:00:01 -w 1', {idPort: 0x100});
assert.strictEqual(altId.exitCode, 0); checkCleanup(altId);
const noCard = run('EL3TX', '-d 02:00:00:00:00:01 -w 1', {cardPresent: false});
assert.strictEqual(noCard.exitCode, 2); assert.match(noCard.output, /RESULT FAIL code=3/); checkCleanup(noCard);

for (const args of [
  '', '-d 00:00:00:00:00', '-d 02:00:00:00:00:01 -s 2',
  '-d 02:00:00:00:00:01 -p #0F0', '-d 02:00:00:00:00:01 -b #3F0',
  '-d 02:00:00:00:00:01 -t #05FF', '-d 02:00:00:00:00:01 -l 13',
  '-d 02:00:00:00:00:01 -l 1515', '-d 02:00:00:00:00:01 -n 0',
  '-d 02:00:00:00:00:01 -n 101', '-d 02:00:00:00:00:01 -w 0',
  '-d 02:00:00:00:00:01 -w 10001', '-d 02:00:00:00:00:01 -f 11',
]) {
  const result = run('EL3TX', args);
  assert.strictEqual(result.exitCode, 1, args); assert.match(result.output, /RESULT FAIL code=2/); checkCleanup(result);
}
for (const args of ['-x -x', '-s 2', '-n 0', '-n 101', '-w 0', '-w 10001', '-d 02:00:00:00:00:01']) {
  const result = run('EL3RX', args);
  assert.strictEqual(result.exitCode, 1, args); assert.match(result.output, /RESULT FAIL code=2/); checkCleanup(result);
}

const delayed = run('EL3TX', '-d 02:00:00:00:00:01 -w 5', {linkDelay: 4});
assert.strictEqual(delayed.exitCode, 0); checkCleanup(delayed);
const linkDown = run('EL3TX', '-d 02:00:00:00:00:01 -w 2', {link: false});
assert.strictEqual(linkDown.exitCode, 3); assert.match(linkDown.output, /RESULT FAIL code=20/); assert.match(linkDown.output, /waitq=#0002/); checkCleanup(linkDown);

// RX individual/broadcast filtering, foreign-unicast rejection and discard.
const individual = rxFrame(cardMac, 3, 60);
const broad = rxFrame(broadcast, 4, 61);
const other = rxFrame(foreign, 5, 62);
const filtered = run('EL3RX', '-n 2 -w 2', {rxFrames: [other, individual, broad]});
assert.strictEqual(filtered.exitCode, 0);
assert.strictEqual(filtered.rejectedFrames.length, 1);
assert.strictEqual(filtered.rxRemaining, 0);
assert.match(filtered.output, new RegExp(`CRC32=#${crc32(individual).toString(16).padStart(8, '0').toUpperCase()}`));
assert.match(filtered.output, new RegExp(`CRC32=#${crc32(broad).toString(16).padStart(8, '0').toUpperCase()}`));
checkCleanup(filtered);

for (const length of [60, 61, 62, 63, 1514]) {
  for (const sequence of [0x00, 0x55, 0xaa, 0xff, 9]) {
    const frame = rxFrame(cardMac, sequence, length, 0x0600);
    const result = run('EL3RX', '-n 1 -w 2', {rxFrames: [frame]});
    assert.strictEqual(result.exitCode, 0);
    assert.match(result.output, new RegExp(`LENGTH=#${length.toString(16).padStart(4, '0').toUpperCase()}`));
    assert.match(result.output, new RegExp(`CRC32=#${crc32(frame).toString(16).padStart(8, '0').toUpperCase()}`));
    checkCleanup(result);
  }
}

for (const count of [2, 10]) {
  const frames = Array.from({length: count}, (_, i) => rxFrame(cardMac, i, 60));
  const result = run('EL3RX', `-n ${count} -w 2`, {rxFrames: frames});
  assert.strictEqual(result.exitCode, 0);
  assert.strictEqual((result.output.match(/\[R2\]/g) || []).length, count);
  assert.strictEqual(result.rxRemaining, 0);
  checkCleanup(result);
}

const dumpFrame = rxFrame(cardMac, 0x20, 60);
const dump = run('EL3RX', '-x -n 1 -w 2', {rxFrames: [dumpFrame]});
assert.strictEqual(dump.exitCode, 0); assert.match(dump.output, /0000:/); assert.match(dump.output, /\|/); checkCleanup(dump);
const rxTimeout = run('EL3RX', '-n 1 -w 2');
assert.strictEqual(rxTimeout.exitCode, 3); assert.match(rxTimeout.output, /RESULT FAIL code=14/); checkCleanup(rxTimeout);

for (const slot of [0, 1]) {
  const frame = rxFrame(cardMac, slot, 60);
  const result = run('EL3RX', `-s ${slot} -n 1 -w 1`, {slot, rxFrames: [frame]});
  assert.strictEqual(result.exitCode, 0); checkCleanup(result);
}
for (const base of [0x200, 0x300, 0x3e0]) {
  const frame = rxFrame(cardMac, base >> 4, 60);
  const result = run('EL3RX', `-b #${base.toString(16).toUpperCase()} -n 1 -w 1`, {rxFrames: [frame]});
  assert.strictEqual(result.exitCode, 0); assert.strictEqual(result.card.base, base); checkCleanup(result);
}
const rxNoCard = run('EL3RX', '-n 1 -w 1', {cardPresent: false});
assert.strictEqual(rxNoCard.exitCode, 2); assert.match(rxNoCard.output, /RESULT FAIL code=3/); checkCleanup(rxNoCard);
const rxDelayed = run('EL3RX', '-n 1 -w 5', {linkDelay: 4, rxFrames: [rxFrame(cardMac, 1)]});
assert.strictEqual(rxDelayed.exitCode, 0); checkCleanup(rxDelayed);
const rxLinkDown = run('EL3RX', '-n 1 -w 2', {link: false, rxFrames: [rxFrame(cardMac, 1)]});
assert.strictEqual(rxLinkDown.exitCode, 3); assert.match(rxLinkDown.output, /RESULT FAIL code=20/); checkCleanup(rxLinkDown);

console.log(`Actual DSS EXE harness: ${cases} header, EL3LB, TX/RX vector, CLI, link, filter, CRC32 and cleanup checks passed`);
