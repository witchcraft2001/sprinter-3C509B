	DEVICE NOSLOT64K
	INCLUDE "memory.inc"
	INCLUDE "el3.inc"

TEST_RESULT	EQU 0xC000
TEST_INDEX	EQU 0xC001
TEST_COMPLETE	EQU 0xC002

	ORG 0x4000
TEST_START
	LD	A,0xFF
	LD	(TEST_RESULT),A
	XOR	A
	LD	(TEST_COMPLETE),A

; Full 255-byte activation sequence against an independently generated vector.
	LD	HL,LFSR_GOLDEN
	LD	A,EL3_LFSR_SEED
	LD	B,0xFF
.LFSR_LOOP
	CP	(HL)
	JP	NZ,FAIL_1
	INC	HL
	CALL	@EL3ALG.LFSR_NEXT
	DJNZ	.LFSR_LOOP
	CP	EL3_LFSR_SEED
	JP	NZ,FAIL_2

; Every one of the 31 base encodings must round-trip.
	XOR	A
	LD	(TEST_INDEX),A
.BASE_LOOP
	LD	A,(TEST_INDEX)
	CALL	@EL3ALG.BASE_DECODE
	JP	C,FAIL_3
	CALL	@EL3ALG.BASE_ENCODE
	JP	C,FAIL_4
	LD	B,A
	LD	A,(TEST_INDEX)
	CP	B
	JP	NZ,FAIL_5
	INC	A
	LD	(TEST_INDEX),A
	CP	EL3_BASE_COUNT
	JR	NZ,.BASE_LOOP
	LD	A,EL3_BASE_COUNT
	CALL	@EL3ALG.BASE_DECODE
	JP	NC,FAIL_6
	LD	HL,0x01F0
	CALL	@EL3ALG.BASE_ENCODE
	JP	NC,FAIL_7
	LD	HL,0x03F0
	CALL	@EL3ALG.BASE_ENCODE
	JP	NC,FAIL_8

; Golden EEPROM, exact IDs, MAC byte order, and checksum lanes.
	LD	HL,EEPROM_GOLDEN
	LD	DE,EEPROM_BUFFER
	LD	BC,128
	LDIR
	CALL	@EL3ALG.VALIDATE
	JP	C,FAIL_9
	LD	HL,EL3_MAC
	LD	DE,MAC_GOLDEN
	LD	B,6
.MAC_LOOP
	LD	A,(DE)
	CP	(HL)
	JP	NZ,FAIL_10
	INC	DE
	INC	HL
	DJNZ	.MAC_LOOP
	LD	HL,EEPROM_BUFFER + 0x0F*2 + 1
	LD	A,(HL)
	XOR	1
	LD	(HL),A
	CALL	@EL3ALG.VALIDATE
	JP	NC,FAIL_11
	CP	EL3_ERR_CHECKSUM
	JP	NZ,FAIL_11
	LD	A,(HL)
	XOR	1
	LD	(HL),A
	LD	HL,EEPROM_BUFFER + 0x17*2
	LD	A,(HL)
	XOR	1
	LD	(HL),A
	CALL	@EL3ALG.VALIDATE
	JP	NC,FAIL_12
	CP	EL3_ERR_CHECKSUM
	JP	NZ,FAIL_12
	LD	A,(HL)
	XOR	1
	LD	(HL),A
	LD	HL,EEPROM_BUFFER + 0x03*2
	LD	A,(HL)
	XOR	1
	LD	(HL),A
	CALL	@EL3ALG.VALIDATE
	JP	NC,FAIL_13
	CP	EL3_ERR_NOT_FOUND
	JP	NZ,FAIL_13

; EL3INFO minimum and maximum numeric boundaries.
	LD	HL,CMD_INFO_MIN
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	C,FAIL_14
	LD	A,(CLI_SLOT)
	OR	A
	JP	NZ,FAIL_14
	LD	HL,(CLI_IDPORT)
	LD	DE,0x0100
	OR	A
	SBC	HL,DE
	JP	NZ,FAIL_14
	LD	HL,(CLI_BASE)
	LD	DE,0x0200
	OR	A
	SBC	HL,DE
	JP	NZ,FAIL_14
	LD	A,(CLI_VERBOSE)
	CP	1
	JP	NZ,FAIL_14

	LD	HL,CMD_INFO_MAX
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	C,FAIL_15
	LD	HL,(CLI_IDPORT)
	LD	DE,0x01F0
	OR	A
	SBC	HL,DE
	JP	NZ,FAIL_15
	LD	HL,(CLI_BASE)
	LD	DE,0x03E0
	OR	A
	SBC	HL,DE
	JP	NZ,FAIL_15

; Rejected just-outside boundaries and accepted AUTO.
	LD	HL,CMD_BAD_ID_LOW
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	NC,FAIL_16
	LD	HL,CMD_BAD_ID_HIGH
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	NC,FAIL_17
	LD	HL,CMD_BAD_BASE
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	NC,FAIL_18
	LD	HL,CMD_AUTO
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_INFO
	JP	C,FAIL_19
	LD	A,(CLI_BASE_AUTO)
	CP	1
	JP	NZ,FAIL_19

; Explicit probe bounds, inclusive end at 4000h, and mandatory tuple.
	LD	HL,CMD_PROBE_MIN
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_PROBE
	JP	C,FAIL_20
	LD	HL,CMD_PROBE_MAX
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_PROBE
	JP	C,FAIL_21
	LD	HL,CMD_PROBE_CROSS
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_PROBE
	JP	NC,FAIL_22
	LD	HL,CMD_PROBE_MISSING
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_PROBE
	JP	NC,FAIL_23
	LD	HL,CMD_EEP_MAX
	LD	(CMDLINE_SOURCE),HL
	CALL	@CLI.PARSE_EEP
	JP	C,FAIL_24
	LD	A,0xA5
	LD	(TEST_COMPLETE),A
	XOR	A
	LD	(TEST_RESULT),A
	JR	TEST_DONE

FAIL_1:  LD A,1
	JR FAIL
FAIL_2:  LD A,2
	JR FAIL
FAIL_3:  LD A,3
	JR FAIL
FAIL_4:  LD A,4
	JR FAIL
FAIL_5:  LD A,5
	JR FAIL
FAIL_6:  LD A,6
	JR FAIL
