EXE_VERSION	EQU 1
SCAN_C		EQU 0xAC		; DSS positional scancode for C with bit 7 set
DHCP_SERVER_TEXT EQU 0x6100
DHCP_LEASE_TEXT EQU 0x6120
DHCP_OLD_IP	EQU 0x6200
DHCP_OLD_MASK	EQU 0x6204
DHCP_OLD_ROUTER EQU 0x6208
DHCP_OLD_DNS1	EQU 0x620C
DHCP_OLD_DNS2	EQU 0x6210
DHCP_OLD_LEASE	EQU 0x6214
IFUP_MODE_NORMAL EQU 0
IFUP_MODE_RENEW EQU 1
IFUP_MODE_RELEASE EQU 2
	DEFINE RUNTIME_BASE 0x7000
	DEFINE STAGE9_LAYOUT
	DEFINE STAGE10_PAGE_LAYOUT

	DEVICE NOSLOT64K
	INCLUDE "version.inc"
	INCLUDE "dss.inc"
