EXE_VERSION	EQU 1
	DEVICE NOSLOT64K
	INCLUDE "version.inc"
	INCLUDE "dss.inc"
	INCLUDE "macro.inc"
	INCLUDE "memory.inc"
	INCLUDE "el3.inc"

	MODULE MAIN
	ORG 0x8080
	DB "EXE",EXE_VERSION
	DW 0x0080,0,0,0,0,0
	DW START,START,STACK_TOP
	DS 106,0
	ORG 0x8100
START
	LD	(CMDLINE_SOURCE),IX
	LD	SP,STACK_TOP
	LD	A,EL3_STAGE_ARGS
	LD	(EL3_LAST_STAGE),A
	XOR	A
	LD	H,A
	LD	L,A
	LD	(CLI_BASE),HL
	LD	(CLI_COUNT),HL
	LD	HL,MSG_BANNER
	CALL	@CONSOLE.LINE
	CALL	@CLI.PARSE_PROBE
	JR	C,PARSE_RESULT
	LD	HL,(CLI_BASE)
	LD	(CURRENT_PORT),HL
	LD	HL,(CLI_COUNT)
	LD	(REMAINING),HL
	LD	A,EL3_STAGE_PROBE
	LD	(EL3_LAST_STAGE),A
	CALL	PRINT_E0
	CALL	DUMP_RANGE
	JP	C,FAIL
	JP	SUCCESS

PARSE_RESULT
	CP	EL3_CLI_HELP
	JR	NZ,.MISSING_OR_BAD
	CALL	PRINT_HELP
	JP	SUCCESS
.MISSING_OR_BAD
	LD	(FAIL_CODE),A
	CALL	PRINT_HELP
	LD	A,(FAIL_CODE)
	JP	FAIL

PRINT_HELP
	LD	HL,MSG_HELP_1
	CALL	@CONSOLE.LINE
	LD	HL,MSG_HELP_2
	JP	@CONSOLE.LINE

PRINT_E0
	LD	HL,MSG_E0_SLOT
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_BASE
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_BASE)
	CALL	@CONSOLE.HEX16
	LD	HL,MSG_COUNT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_COUNT)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	JP	@CONSOLE.STRING

DUMP_RANGE
.ROW
	LD	HL,(REMAINING)
	LD	A,H
	OR	L
	JR	Z,.DONE
	LD	A,H
	OR	A
	JR	NZ,.FULL
	LD	A,L
	CP	16
	JR	C,.HAVE_LENGTH
.FULL
	LD	A,16
.HAVE_LENGTH
	LD	(ROW_LENGTH),A
	LD	A,(CLI_SLOT)
	CALL	@ISA.OPEN
	JR	C,.ISA_ERROR
	LD	BC,(CURRENT_PORT)
	CALL	@ISA.MAP_POINTER
	LD	DE,PROBE_ROW
	LD	A,(ROW_LENGTH)
	LD	B,A
.COPY
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	DJNZ	.COPY
	CALL	@ISA.CLOSE
	JR	C,.ISA_ERROR
	CALL	PRINT_ROW
	LD	A,(ROW_LENGTH)
	LD	E,A
	LD	D,0
	LD	HL,(CURRENT_PORT)
	ADD	HL,DE
	LD	(CURRENT_PORT),HL
	LD	HL,(REMAINING)
	OR	A
	SBC	HL,DE
	LD	(REMAINING),HL
	JR	.ROW
.DONE
	XOR	A
	RET
.ISA_ERROR
	LD	A,EL3_ERR_ISA_STATE
	SCF
	RET

PRINT_ROW
	LD	HL,MSG_E6
	CALL	@CONSOLE.STRING
	LD	HL,(CURRENT_PORT)
	CALL	@CONSOLE.HEX16
	LD	A,':'
	CALL	@CONSOLE.CHAR
	LD	HL,PROBE_ROW
	LD	A,(ROW_LENGTH)
	LD	B,A
.LOOP
	LD	A,' '
	CALL	@CONSOLE.CHAR
	LD	A,(HL)
	CALL	@CONSOLE.HEX8
	INC	HL
	DJNZ	.LOOP
	LD	HL,@CONSOLE.CRLF
	JP	@CONSOLE.STRING

FAIL
	LD	(FAIL_CODE),A
	LD	HL,MSG_ERROR_STAGE
	CALL	@CONSOLE.STRING
	LD	A,(EL3_LAST_STAGE)
	CALL	@CONSOLE.HEX8
	LD	HL,MSG_ERROR_CODE
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_ERROR_SLOT
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_ERROR_BASE
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_BASE)
	CALL	@CONSOLE.HEX16
	LD	HL,MSG_ERROR_COUNT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_COUNT)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	HL,MSG_RESULT_FAIL
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	LD	B,A
	LD	C,DSS_EXIT
	RST	DSS

SUCCESS
	LD	HL,MSG_RESULT_OK
	CALL	@CONSOLE.LINE
	DSS_RETURN 0

MSG_BANNER	DB "3C509B ISAPROBE v",PACKAGE_VERSION,0
MSG_HELP_1	DB "Usage: ISAPROBE -s 0|1 -b #0000..#3FFF",0
MSG_HELP_2	DB "                -n #0001..#0100 (read-only)",0
MSG_E0_SLOT	DB "[E0] SLOT=",0
MSG_BASE	DB " BASE=",0
MSG_COUNT	DB " COUNT=",0
MSG_E6		DB "[E6] ",0
MSG_ERROR_STAGE DB "ERROR stage=",0
MSG_ERROR_CODE	DB " code=",0
MSG_ERROR_SLOT	DB " slot=",0
MSG_ERROR_BASE	DB " base=",0
MSG_ERROR_COUNT DB " count=",0
MSG_RESULT_OK	DB "RESULT OK",0
MSG_RESULT_FAIL	DB "RESULT FAIL code=",0
CURRENT_PORT	DW 0
REMAINING	DW 0
ROW_LENGTH	DB 0
FAIL_CODE	DB 0
	ENDMODULE

	INCLUDE "el3_algorithms.asm"
	INCLUDE "cli.asm"
	INCLUDE "console.asm"
	INCLUDE "isa.asm"
