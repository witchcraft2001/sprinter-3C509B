EXE_VERSION	EQU 1
	DEVICE NOSLOT64K
	INCLUDE "version.inc"
	INCLUDE "dss.inc"
	INCLUDE "macro.inc"
	INCLUDE "memory.inc"
	INCLUDE "el3.inc"

	MODULE MAIN
	ORG 0x8080
	DB "EXE",EXE_VERSION
	DW 0x0080,0,0,0,0,0
	DW START,START,STACK_TOP
	DS 106,0
	ORG 0x8100
START
	LD	(CMDLINE_SOURCE),IX
	LD	SP,STACK_TOP
	LD	A,EL3_STAGE_ARGS
	LD	(EL3_LAST_STAGE),A
	XOR	A
	LD	H,A
	LD	L,A
	LD	(EL3_LAST_TICKS),HL
	LD	(EL3_LAST_STATUS),HL
	LD	HL,MSG_BANNER
	CALL	@CONSOLE.LINE
	CALL	@CLI.PARSE_EEP
	JR	C,PARSE_RESULT
	LD	A,(CLI_SLOT)
	LD	HL,(CLI_IDPORT)
	CALL	@EL3.CONFIGURE
	JR	C,FAIL
	CALL	PRINT_E0
	CALL	@EL3.DISCOVER
	JR	C,FAIL
	CALL	PRINT_DUMP
	JP	SUCCESS

PARSE_RESULT
	CP	EL3_CLI_HELP
	JR	NZ,.BAD
	CALL	PRINT_HELP
	JP	SUCCESS
.BAD
	LD	(FAIL_CODE),A
	CALL	PRINT_HELP
	LD	A,(FAIL_CODE)
	JR	FAIL

PRINT_E0
	LD	HL,MSG_E0
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_IDPORT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_IDPORT)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	JP	@CONSOLE.STRING

PRINT_DUMP
	LD	HL,MSG_E1
	CALL	@CONSOLE.LINE
	LD	HL,EEPROM_BUFFER
	LD	B,0
.LOOP
	LD	A,B
	CALL	@CONSOLE.HEX8
	LD	A,':'
	CALL	@CONSOLE.CHAR
	LD	A,' '
	CALL	@CONSOLE.CHAR
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	INC	HL
	PUSH	HL
	EX	DE,HL
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	POP	HL
	INC	B
	LD	A,B
	CP	0x40
	JR	NZ,.LOOP
	LD	HL,MSG_E2
	JP	@CONSOLE.LINE

PRINT_HELP
	LD	HL,MSG_HELP
	JP	@CONSOLE.LINE

FAIL
	LD	(FAIL_CODE),A
	LD	HL,MSG_ERROR
	CALL	@CONSOLE.STRING
	LD	A,(EL3_LAST_STAGE)
	CALL	@CONSOLE.HEX8
	LD	HL,MSG_CODE
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_TICKS
	CALL	@CONSOLE.STRING
	LD	A,(EL3_LAST_TICKS)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_SLOT
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_ERROR_IDPORT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_IDPORT)
	CALL	@CONSOLE.HEX16
	LD	HL,MSG_STATUS
	CALL	@CONSOLE.STRING
	LD	HL,(EL3_LAST_STATUS)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	HL,MSG_RESULT_FAIL
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	LD	B,A
	LD	C,DSS_EXIT
	RST	DSS

SUCCESS
	LD	HL,MSG_RESULT_OK
	CALL	@CONSOLE.LINE
	DSS_RETURN 0

MSG_BANNER	DB "3C509B EL3EEP v",PACKAGE_VERSION,0
MSG_E0		DB "[E0] SLOT=",0
MSG_IDPORT	DB " IDPORT=",0
MSG_E1		DB "[E1] EEPROM WORDS 00..3F",0
MSG_E2		DB "[E2] IDS MAC CHECKSUMS VALID",0
MSG_HELP	DB "Usage: EL3EEP [-s 0|1] [-p #100..#1F0]",0
MSG_ERROR	DB "ERROR stage=",0
MSG_CODE	DB " code=",0
MSG_TICKS	DB " waitq=",0
MSG_SLOT	DB " slot=",0
MSG_ERROR_IDPORT DB " idport=",0
MSG_STATUS	DB " status=",0
MSG_RESULT_OK	DB "RESULT OK",0
MSG_RESULT_FAIL	DB "RESULT FAIL code=",0
FAIL_CODE	DB 0
	ENDMODULE

	INCLUDE "el3_algorithms.asm"
	INCLUDE "cli.asm"
	INCLUDE "console.asm"
	INCLUDE "isa.asm"
	INCLUDE "el3_io.asm"
	INCLUDE "el3_regs.asm"
	INCLUDE "el3.asm"
