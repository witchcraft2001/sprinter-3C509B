EXE_VERSION	EQU 1
; EL3EEP is the developer EEPROM tool and ships in the diagnostic IMG only, so
; it carries the VALIDATE diagnostics. Every other application leaves
; EL3_VALIDATE_DIAG undefined and is unchanged byte for byte.
	DEFINE EL3_VALIDATE_DIAG
	DEVICE NOSLOT64K
	INCLUDE "version.inc"
	INCLUDE "dss.inc"
	INCLUDE "macro.inc"
	INCLUDE "memory.inc"
	INCLUDE "el3.inc"

	MODULE MAIN
	ORG 0x8080
	DB "EXE",EXE_VERSION
	DW 0x0080,0,0,0,0,0
	DW START,START,STACK_TOP
	DS 106,0
	ORG 0x8100
START
	LD	(CMDLINE_SOURCE),IX
	LD	SP,STACK_TOP
	LD	A,EL3_STAGE_ARGS
	LD	(EL3_LAST_STAGE),A
	XOR	A
	LD	H,A
	LD	L,A
	LD	(EL3_LAST_TICKS),HL
	LD	(EL3_LAST_STATUS),HL
	LD	(EL3_PRIMARY_CALC),HL
	LD	(EL3_SECONDARY_CALC),HL
	LD	(EL3_VALIDATE_FAIL),A
	LD	HL,MSG_BANNER
	CALL	@CONSOLE.LINE
	CALL	@CLI.PARSE_EEP
	JR	C,PARSE_RESULT
	LD	A,(CLI_SLOT)
	LD	HL,(CLI_IDPORT)
	CALL	@EL3.CONFIGURE
	JP	C,FAIL
	CALL	PRINT_E0
	CALL	@EL3.DISCOVER
	JR	C,DISCOVER_FAILED
	CALL	PRINT_DUMP
	LD	HL,MSG_E2
	CALL	@CONSOLE.LINE
	JP	SUCCESS

; A rejected image is the whole point of running this on an unknown card, so
; the words are printed exactly as they were read before the error line.
DISCOVER_FAILED
	LD	(FAIL_CODE),A
	LD	A,(EL3_LAST_STAGE)
	CP	EL3_STAGE_VALIDATE
	JR	NZ,.NO_DUMP
	CALL	PRINT_DUMP
	CALL	PRINT_DIAG
.NO_DUMP
	LD	A,(FAIL_CODE)
	JP	FAIL

PARSE_RESULT
	CP	EL3_CLI_HELP
	JR	NZ,.BAD
	CALL	PRINT_HELP
	JP	SUCCESS
.BAD
	LD	(FAIL_CODE),A
	CALL	PRINT_HELP
	LD	A,(FAIL_CODE)
	JP	FAIL

PRINT_E0
	LD	HL,MSG_E0
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_IDPORT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_IDPORT)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	JP	@CONSOLE.STRING

; Eight words per line keeps the whole EEPROM inside one screen, so a single
; photograph of a real card carries the complete evidence.
PRINT_DUMP
	LD	HL,MSG_E1
	CALL	@CONSOLE.LINE
	LD	HL,EEPROM_BUFFER
	LD	B,0
.ROW
	LD	A,B
	CALL	@CONSOLE.HEX8
	LD	A,':'
	CALL	@CONSOLE.CHAR
	LD	C,8
.WORD
	LD	A,' '
	CALL	@CONSOLE.CHAR
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	INC	HL
	PUSH	BC,HL
	EX	DE,HL
	CALL	@CONSOLE.HEX16
	POP	HL,BC
	DEC	C
	JR	NZ,.WORD
	PUSH	BC,HL
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	POP	HL,BC
	LD	A,B
	ADD	A,8
	LD	B,A
	CP	0x40
	JR	NZ,.ROW
	RET

; Both checksum lanes are printed as EEPROM/computed in word order, so a lane
; swap, a different word set and an unreadable EEPROM are told apart at a
; glance instead of by a single "code=5".
PRINT_DIAG
	LD	HL,MSG_E3
	CALL	@CONSOLE.STRING
	LD	A,(EL3_VALIDATE_FAIL)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_PRIMARY
	CALL	@CONSOLE.STRING
	LD	HL,(EEPROM_BUFFER + 0x0F*2)
	CALL	@CONSOLE.HEX16
	LD	A,'/'
	CALL	@CONSOLE.CHAR
	LD	HL,(EL3_PRIMARY_CALC)
	CALL	@CONSOLE.HEX16
	LD	HL,MSG_SECOND
	CALL	@CONSOLE.STRING
	LD	HL,(EEPROM_BUFFER + 0x17*2)
	CALL	@CONSOLE.HEX16
	LD	A,'/'
	CALL	@CONSOLE.CHAR
	LD	HL,(EL3_SECONDARY_CALC)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	JP	@CONSOLE.STRING

PRINT_HELP
	LD	HL,MSG_HELP
	JP	@CONSOLE.LINE

FAIL
	LD	(FAIL_CODE),A
	LD	HL,MSG_ERROR
	CALL	@CONSOLE.STRING
	LD	A,(EL3_LAST_STAGE)
	CALL	@CONSOLE.HEX8
	LD	HL,MSG_CODE
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_TICKS
	CALL	@CONSOLE.STRING
	LD	A,(EL3_LAST_TICKS)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_SLOT
	CALL	@CONSOLE.STRING
	LD	A,(CLI_SLOT)
	CALL	@CONSOLE.DEC8
	LD	HL,MSG_ERROR_IDPORT
	CALL	@CONSOLE.STRING
	LD	HL,(CLI_IDPORT)
	CALL	@CONSOLE.HEX16
	LD	HL,MSG_STATUS
	CALL	@CONSOLE.STRING
	LD	HL,(EL3_LAST_STATUS)
	CALL	@CONSOLE.HEX16
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	HL,MSG_RESULT_FAIL
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@CONSOLE.DEC8
	LD	HL,@CONSOLE.CRLF
	CALL	@CONSOLE.STRING
	LD	A,(FAIL_CODE)
	CALL	@EL3ALG.TO_DSS_EXIT
	LD	C,DSS_EXIT
	RST	DSS

SUCCESS
	LD	HL,MSG_RESULT_OK
	CALL	@CONSOLE.LINE
	DSS_RETURN 0

MSG_BANNER	DB "3C509B EL3EEP v",PACKAGE_VERSION,0
MSG_E0		DB "[E0] SLOT=",0
MSG_IDPORT	DB " IDPORT=",0
MSG_E1		DB "[E1] EEPROM WORDS 00..3F",0
MSG_E2		DB "[E2] IDS MAC CHECKSUMS VALID",0
MSG_E3		DB "[E3] FAIL=",0
MSG_PRIMARY	DB " PRI=",0
MSG_SECOND	DB " SEC=",0
MSG_HELP	DB "Usage: EL3EEP [-s 0|1] [-p #100..#1F0]",0
MSG_ERROR	DB "ERROR stage=",0
MSG_CODE	DB " code=",0
MSG_TICKS	DB " waitq=",0
MSG_SLOT	DB " slot=",0
MSG_ERROR_IDPORT DB " idport=",0
MSG_STATUS	DB " status=",0
MSG_RESULT_OK	DB "RESULT OK",0
MSG_RESULT_FAIL	DB "RESULT FAIL code=",0
FAIL_CODE	DB 0
	ENDMODULE

	INCLUDE "el3_algorithms.asm"
	INCLUDE "cli.asm"
	INCLUDE "console.asm"
	INCLUDE "isa.asm"
	INCLUDE "el3_io.asm"
	INCLUDE "el3_fifo.asm"
	INCLUDE "el3_regs.asm"
	INCLUDE "el3.asm"
