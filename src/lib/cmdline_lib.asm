	IFNDEF	_CMDLINE_LIB_ASM
	DEFINE	_CMDLINE_LIB_ASM

	INCLUDE "memory.inc"
	INCLUDE "el3.inc"
	INCLUDE "netdrv.inc"

	MODULE CMDLINE

SEEN_T		EQU 0x01
SEEN_N		EQU 0x02
SEEN_L		EQU 0x04
SEEN_I		EQU 0x08
SEEN_W		EQU 0x10
SEEN_TARGET	EQU 0x20
SEEN_HELP	EQU 0x40

; PARSE_PING implements the public PING/PINGALT grammar. It performs no DSS,
; NETDRV or ISA operation, so every syntax error is rejected before hardware.
; Out: A=0/CF=0, EL3_CLI_HELP/CF=1, or NETDRV_ERR_PARAMETER/CF=1.
PARSE_PING
	PUSH	IX,IY
	XOR	A
	LD	(PING_FLAGS),A
	LD	(PING_SEEN),A
	LD	(PING_HELP),A
	LD	HL,4
	LD	(PING_COUNT),HL
	LD	HL,32
	LD	(PING_SIZE),HL
	LD	HL,1000
	LD	(PING_TIMEOUT_MS),HL
	LD	A,64
	LD	(PING_TTL),A
	CALL	READER_INIT
.TOKEN_LOOP
	CALL	NEXT_TOKEN
	JP	C,.END_ARGS
	LD	A,(HL)
	CP	'-'
	JR	Z,.FLAG
	CP	'/'
	JR	Z,.FLAG
	LD	A,SEEN_TARGET
	CALL	MARK_UNIQUE
	JP	C,.BAD
	LD	DE,PING_TARGET_TEXT
	LD	C,16
	CALL	COPY_TOKEN_Z
	JP	C,.BAD
	LD	HL,PING_TARGET_TEXT
	LD	DE,NET_TARGET_IP
	CALL	@NETPARSE.PARSE_IPV4
	JP	C,.BAD
	JP	.TOKEN_LOOP
.FLAG
	LD	A,(CLI_TOKEN_LEN)
	CP	2
	JP	NZ,.BAD
	INC	HL
	LD	A,(HL)
	CALL	UPPER_A
	CP	'?'
	JR	Z,.HELP
	CP	'H'
	JR	Z,.HELP
	CP	'T'
	JR	Z,.INFINITE
	CP	'N'
	JR	Z,.COUNT
	CP	'L'
	JR	Z,.SIZE
	CP	'I'
	JR	Z,.TTL
	CP	'W'
	JP	Z,.WAIT
	JP	.BAD
.HELP
	LD	A,SEEN_HELP
	CALL	MARK_UNIQUE
	JP	C,.BAD
	LD	A,1
	LD	(PING_HELP),A
	JP	.TOKEN_LOOP
.INFINITE
	LD	A,SEEN_T
	CALL	MARK_UNIQUE
	JP	C,.BAD
	LD	A,PING_FLAG_INFINITE
	LD	(PING_FLAGS),A
	JP	.TOKEN_LOOP
.COUNT
	LD	A,SEEN_N
	CALL	MARK_UNIQUE
	JP	C,.BAD
	CALL	NEXT_TOKEN
	JP	C,.BAD
	CALL	PARSE_U16
	JP	C,.BAD
	LD	A,B
	OR	C
	JP	Z,.BAD
	LD	(PING_COUNT),BC
	JP	.TOKEN_LOOP
.SIZE
	LD	A,SEEN_L
	CALL	MARK_UNIQUE
	JP	C,.BAD
	CALL	NEXT_TOKEN
	JP	C,.BAD
	CALL	PARSE_SIZE
	JP	C,.BAD
	LD	HL,1472
	OR	A
	SBC	HL,BC
	JP	C,.BAD
	LD	(PING_SIZE),BC
	JP	.TOKEN_LOOP
.TTL
	LD	A,SEEN_I
	CALL	MARK_UNIQUE
	JP	C,.BAD
	CALL	NEXT_TOKEN
	JP	C,.BAD
	CALL	PARSE_U16
	JP	C,.BAD
	LD	A,B
	OR	A
	JP	NZ,.BAD
	LD	A,C
	OR	A
	JP	Z,.BAD
	LD	(PING_TTL),A
	JP	.TOKEN_LOOP
.WAIT
	LD	A,SEEN_W
	CALL	MARK_UNIQUE
	JP	C,.BAD
	CALL	NEXT_TOKEN
	JP	C,.BAD
	CALL	PARSE_U16
	JP	C,.BAD
	LD	A,B
	OR	C
	JP	Z,.BAD
	LD	(PING_TIMEOUT_MS),BC
	JP	.TOKEN_LOOP
.END_ARGS
	LD	A,(PING_SEEN)
	AND	SEEN_HELP
	JR	Z,.NOT_HELP
	LD	A,(PING_SEEN)
	CP	SEEN_HELP
	JR	NZ,.BAD
	LD	A,EL3_CLI_HELP
	SCF
	POP	IY,IX
	RET
.NOT_HELP
	LD	A,(PING_SEEN)
	AND	SEEN_TARGET
	JR	Z,.BAD
	LD	A,(PING_SEEN)
	AND	SEEN_T | SEEN_N
	CP	SEEN_T | SEEN_N
	JR	Z,.BAD
	XOR	A
	POP	IY,IX
	RET
.BAD
	LD	A,NETDRV_ERR_PARAMETER
	SCF
	POP	IY,IX
	RET

READER_INIT
	LD	HL,(CMDLINE_SOURCE)
	LD	A,(HL)
	INC	HL
	LD	(CLI_READER_PTR),HL
	LD	(CLI_READER_REMAIN),A
	RET

; NEXT_TOKEN returns HL=start and CLI_TOKEN_LEN, bounded by the DSS byte count.
NEXT_TOKEN
	LD	HL,(CLI_READER_PTR)
	LD	A,(CLI_READER_REMAIN)
	LD	B,A
.SKIP
	LD	A,B
	OR	A
	JR	Z,.NONE
	LD	A,(HL)
	CP	' '
	JR	Z,.SKIP_ONE
	CP	9
	JR	NZ,.START
.SKIP_ONE
	INC	HL
	DEC	B
	JR	.SKIP
.START
	PUSH	HL
	LD	C,0
.SCAN
	LD	A,B
	OR	A
	JR	Z,.DONE
	LD	A,(HL)
	CP	' '
	JR	Z,.DONE
	CP	9
	JR	Z,.DONE
	INC	HL
	INC	C
	DEC	B
	JR	.SCAN
.DONE
	LD	(CLI_READER_PTR),HL
	LD	A,B
	LD	(CLI_READER_REMAIN),A
	LD	A,C
	LD	(CLI_TOKEN_LEN),A
	POP	HL
	OR	A
	RET
.NONE
	LD	(CLI_READER_PTR),HL
	XOR	A
	LD	(CLI_READER_REMAIN),A
	SCF
	RET

; COPY_TOKEN_Z: HL=token, C=destination capacity, DE=destination.
COPY_TOKEN_Z
	LD	A,(CLI_TOKEN_LEN)
	CP	C
	JR	NC,.COPY_BAD
	LD	B,A
.COPY_LOOP
	LD	A,B
	OR	A
	JR	Z,.COPY_TERM
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	DEC	B
	JR	.COPY_LOOP
.COPY_TERM
	XOR	A
	LD	(DE),A
	RET
.COPY_BAD
	SCF
	RET

; Unsigned decimal 0..65535. Result BC.
PARSE_U16
	LD	A,(CLI_TOKEN_LEN)
	OR	A
	JR	Z,.U16_BAD
	CP	6
	JR	NC,.U16_BAD
	LD	(CMD_PARSE_REMAIN),A
	LD	BC,0
.U16_LOOP
	LD	A,(HL)
	CP	'0'
	JR	C,.U16_BAD
	CP	'9'+1
	JR	NC,.U16_BAD
	SUB	'0'
	LD	(CMD_PARSE_DIGIT),A
	PUSH	HL
	LD	H,B
	LD	L,C
	ADD	HL,HL
	JR	C,.U16_OVERFLOW
	LD	D,H
	LD	E,L
	ADD	HL,HL
	JR	C,.U16_OVERFLOW
	ADD	HL,HL
	JR	C,.U16_OVERFLOW
	ADD	HL,DE
	JR	C,.U16_OVERFLOW
	LD	A,(CMD_PARSE_DIGIT)
	LD	E,A
	LD	D,0
	ADD	HL,DE
	JR	C,.U16_OVERFLOW
	LD	B,H
	LD	C,L
	POP	HL
	INC	HL
	LD	A,(CMD_PARSE_REMAIN)
	DEC	A
	LD	(CMD_PARSE_REMAIN),A
	JR	NZ,.U16_LOOP
	OR	A
	RET
.U16_OVERFLOW
	POP	HL
.U16_BAD
	SCF
	RET

PARSE_PORT
	CALL	PARSE_U16
	RET	C
	LD	A,B
	OR	C
	RET	NZ
	SCF
	RET

PARSE_SIZE
	JP	PARSE_U16

; PARSE_IPV4_TOKEN copies the bounded token and invokes the strict common
; dotted-decimal parser. In: HL token, DE four-byte result.
PARSE_IPV4_TOKEN
	LD	(CMD_PARSE_DEST),DE
	LD	DE,PING_TARGET_TEXT
	LD	C,16
	CALL	COPY_TOKEN_Z
	RET	C
	LD	HL,PING_TARGET_TEXT
	LD	DE,(CMD_PARSE_DEST)
	JP	@NETPARSE.PARSE_IPV4

; Unsigned decimal 0..4294967295. In: HL token, DE=four-byte LE result.
PARSE_U32
	LD	(CMD_PARSE_DEST),DE
	LD	A,(CLI_TOKEN_LEN)
	OR	A
	JR	Z,.U32_BAD
	CP	11
	JR	NC,.U32_BAD
	LD	(CMD_PARSE_REMAIN),A
	XOR	A
	LD	(CMD_U32+0),A
	LD	(CMD_U32+1),A
	LD	(CMD_U32+2),A
	LD	(CMD_U32+3),A
.U32_LOOP
	LD	A,(HL)
	CP	'0'
	JR	C,.U32_BAD
	CP	'9'+1
	JR	NC,.U32_BAD
	SUB	'0'
	LD	(CMD_PARSE_DIGIT),A
	PUSH	HL
	CALL	U32_TIMES10
	POP	HL
	JR	C,.U32_BAD
	LD	A,(CMD_PARSE_DIGIT)
	PUSH	HL
	LD	HL,CMD_U32
	ADD	A,(HL)
	POP	HL
	LD	(CMD_U32+0),A
	JR	NC,.U32_NEXT
	LD	A,(CMD_U32+1)
	INC	A
	LD	(CMD_U32+1),A
	JR	NZ,.U32_NEXT
	LD	A,(CMD_U32+2)
	INC	A
	LD	(CMD_U32+2),A
	JR	NZ,.U32_NEXT
	LD	A,(CMD_U32+3)
	INC	A
	LD	(CMD_U32+3),A
	JR	Z,.U32_BAD
.U32_NEXT
	INC	HL
	LD	A,(CMD_PARSE_REMAIN)
	DEC	A
	LD	(CMD_PARSE_REMAIN),A
	JR	NZ,.U32_LOOP
	LD	HL,CMD_U32
	LD	DE,(CMD_PARSE_DEST)
	LD	BC,4
	LDIR
	XOR	A
	RET
.U32_BAD
	SCF
	RET

; Four-byte LE value *= 10 with overflow detection.
U32_TIMES10
	LD	HL,CMD_U32
	LD	DE,CMD_U32_COPY
	LD	BC,4
	LDIR
	LD	B,3
.SHIFT
	LD	HL,CMD_U32
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C
	DJNZ	.SHIFT			; original * 8
	LD	HL,CMD_U32_COPY
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C			; original * 2 overflow
	LD	HL,CMD_U32
	LD	DE,CMD_U32_COPY
	LD	B,4
	OR	A
.ADD32
	LD	A,(DE)
	ADC	A,(HL)
	LD	(HL),A
	INC	HL
	INC	DE
	DJNZ	.ADD32
	RET

MARK_UNIQUE
	LD	B,A
	LD	A,(PING_SEEN)
	AND	B
	JR	NZ,.DUPLICATE
	LD	A,(PING_SEEN)
	OR	B
	LD	(PING_SEEN),A
	OR	A
	RET
.DUPLICATE
	SCF
	RET

UPPER_A
	CP	'a'
	RET	C
	CP	'z'+1
	RET	NC
	SUB	'a'-'A'
	RET

CMD_PARSE_REMAIN	DB 0
CMD_PARSE_DIGIT		DB 0
CMD_PARSE_DEST		DW 0
CMD_U32		DS 4,0
CMD_U32_COPY		DS 4,0

	ENDMODULE
	ENDIF
