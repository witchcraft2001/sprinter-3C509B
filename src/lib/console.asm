	IFNDEF	_CONSOLE_ASM
	DEFINE	_CONSOLE_ASM

	INCLUDE "dss.inc"

	MODULE CONSOLE

; STRING: HL -> ASCIIZ. Preserves IX and IY.
STRING
	PUSH	IX,IY
	LD	C,DSS_PCHARS
	RST	DSS
	POP	IY,IX
	RET

; LINE: HL -> ASCIIZ, followed by CRLF. Preserves IX and IY.
LINE
	PUSH	IX,IY
	CALL	STRING
	LD	HL,CRLF
	CALL	STRING
	POP	IY,IX
	RET

; CHAR: A = character. Preserves AF, BC, DE, HL, IX and IY.
CHAR
	PUSH	AF,BC,DE,HL,IX,IY
	LD	C,DSS_PUTCHAR
	RST	DSS
	POP	IY,IX,HL,DE,BC,AF
	RET

; HEX8: A = byte. Preserves AF, BC, DE, HL, IX and IY.
HEX8
	PUSH	AF,BC,DE,HL,IX,IY
	LD	B,A
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	HEX_NIBBLE
	LD	A,B
	CALL	HEX_NIBBLE
	POP	IY,IX,HL,DE,BC,AF
	RET

HEX_NIBBLE
	AND	0x0F
	ADD	A,'0'
	CP	'9'+1
	JR	C,.PUT
	ADD	A,'A'-'9'-1
.PUT
	CALL	CHAR
	RET

; HEX16: HL = word. Preserves AF, BC, DE, HL, IX and IY.
HEX16
	PUSH	AF,BC,DE,HL,IX,IY
	LD	A,H
	CALL	HEX8
	LD	A,L
	CALL	HEX8
	POP	IY,IX,HL,DE,BC,AF
	RET

; DEC8: A = unsigned byte. Preserves AF, BC, DE, HL, IX and IY.
DEC8
	PUSH	AF,BC,DE,HL,IX,IY
	LD	B,0
.HUNDREDS
	CP	100
	JR	C,.TENS_START
	SUB	100
	INC	B
	JR	.HUNDREDS
.TENS_START
	LD	C,0
.TENS
	CP	10
	JR	C,.DIGITS
	SUB	10
	INC	C
	JR	.TENS
.DIGITS
	LD	D,A
	LD	A,B
	OR	A
	JR	Z,.NO_HUNDREDS
	ADD	A,'0'
	CALL	CHAR
.NO_HUNDREDS
	LD	A,B
	OR	C
	JR	Z,.NO_TENS
	LD	A,C
	ADD	A,'0'
	CALL	CHAR
.NO_TENS
	LD	A,D
	ADD	A,'0'
	CALL	CHAR
	POP	IY,IX,HL,DE,BC,AF
	RET

; DEC16: HL = unsigned word. Preserves all registers.
DEC16
	PUSH	AF,BC,DE,HL,IX,IY
	LD	DE,CONSOLE_DEC_BUFFER
	CALL	FORMAT_DEC16
	LD	HL,CONSOLE_DEC_BUFFER
	CALL	STRING
	POP	IY,IX,HL,DE,BC,AF
	RET

FORMAT_DEC16
	PUSH	DE
	POP	IY
	LD	IX,CONSOLE_DIVISORS
	LD	B,5
	XOR	A
	LD	(CONSOLE_STARTED),A
.PLACE
	LD	E,(IX+0)
	LD	A,(IX+1)
	LD	(CONSOLE_DIVISOR+1),A
	LD	A,E
	LD	(CONSOLE_DIVISOR),A
	LD	C,0
.SUBTRACT
	LD	DE,(CONSOLE_DIVISOR)
	OR	A
	SBC	HL,DE
	JR	C,.DIGIT
	INC	C
	JR	.SUBTRACT
.DIGIT
	ADD	HL,DE
	LD	A,(CONSOLE_STARTED)
	OR	C
	JR	NZ,.EMIT
	LD	A,B
	CP	1
	JR	NZ,.NEXT_PLACE
.EMIT
	LD	A,C
	ADD	A,'0'
	LD	(IY+0),A
	INC	IY
	LD	A,1
	LD	(CONSOLE_STARTED),A
.NEXT_PLACE
	INC	IX
	INC	IX
	DJNZ	.PLACE
.TERM
	XOR	A
	LD	(IY+0),A
	RET

	IFNDEF STAGE12_LAYOUT
; MAC: HL -> six bytes in network order. Preserves all registers.
MAC
	PUSH	AF,BC,DE,HL,IX,IY
	LD	B,6
.LOOP
	LD	A,(HL)
	CALL	HEX8
	INC	HL
	DEC	B
	JR	Z,.DONE
	LD	A,':'
	CALL	CHAR
	JR	.LOOP
.DONE
	POP	IY,IX,HL,DE,BC,AF
	RET
	ENDIF

CRLF	DB 13,10,0
CONSOLE_DEC_BUFFER DS 6,0
CONSOLE_DIVISORS DW 10000,1000,100,10,1
CONSOLE_DIVISOR DW 0
CONSOLE_STARTED DB 0

	ENDMODULE
	ENDIF
