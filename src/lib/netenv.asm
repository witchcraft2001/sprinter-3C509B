	IFNDEF	_NETENV_ASM
	DEFINE	_NETENV_ASM

	INCLUDE "dss.inc"
	INCLUDE "memory.inc"
	INCLUDE "netdrv.inc"

ENV_VAR_COUNT		EQU 14
ENV_BACKUP_BASE	EQU 0x5000
ENV_BACKUP_SLOT	EQU 257		; present flag + full 256-byte DSS value
ENV_SET_BUFFER		EQU 0x6000

	ASSERT ENV_BACKUP_BASE + ENV_BACKUP_SLOT * ENV_VAR_COUNT < ENV_SET_BUFFER
	ASSERT ENV_SET_BUFFER + 300 < 0x8000

	MODULE NETENV

; GET: HL=name, DE=256-byte destination. Out A=FF found or 0 absent.
GET
	PUSH	IX,IY
	LD	B,ENV_GET
	LD	C,DSS_ENVIRON
	RST	DSS
	POP	IY,IX
	RET

; PUBLISH
; In: HL -> ENV_VAR_COUNT little-endian desired value pointers. A zero pointer
; deletes that variable. Snapshots every old value first and restores the
; complete set after any failed ENV_SET, so callers never expose partial state.
PUBLISH
	PUSH	IX,IY
	LD	(NETENV_DESIRED),HL
	CALL	SNAPSHOT_ALL
	JR	C,.FAIL
	LD	IX,ENV_NAMES
	LD	IY,(NETENV_DESIRED)
	LD	B,ENV_VAR_COUNT
.SET_LOOP
	PUSH	BC,IX,IY
	PUSH	IX
	POP	HL
	LD	E,(IY+0)
	LD	D,(IY+1)
	CALL	SET_ONE
	POP	IY,IX,BC
	JR	C,.ROLLBACK
	CALL	NEXT_NAME_IX
	INC	IY
	INC	IY
	DJNZ	.SET_LOOP
	XOR	A
	POP	IY,IX
	RET
.ROLLBACK
	LD	(NETENV_SAVED_ERROR),A
	CALL	RESTORE_ALL
	LD	A,(NETENV_SAVED_ERROR)
.FAIL
	OR	A
	JR	NZ,.HAVE_ERROR
	LD	A,NETDRV_ERR_CONFIG
.HAVE_ERROR
	SCF
	POP	IY,IX
	RET

; DELETE_ALL uses an all-zero desired table and the same rollback semantics.
DELETE_ALL
	PUSH	IX,IY
	LD	HL,NETENV_EMPTY_DESIRED
	CALL	PUBLISH
	POP	IY,IX
	RET

SNAPSHOT_ALL
	LD	IX,ENV_NAMES
	LD	IY,ENV_BACKUP_BASE
	LD	B,ENV_VAR_COUNT
.LOOP
	PUSH	BC,IX,IY
	PUSH	IX
	POP	HL
	PUSH	IY
	POP	DE
	INC	DE
	CALL	GET
	POP	IY,IX,BC
	LD	(IY+0),A
	CALL	NEXT_NAME_IX
	LD	DE,ENV_BACKUP_SLOT
	ADD	IY,DE
	DJNZ	.LOOP
	XOR	A
	RET

RESTORE_ALL
	LD	IX,ENV_NAMES
	LD	IY,ENV_BACKUP_BASE
	LD	B,ENV_VAR_COUNT
.LOOP
	PUSH	BC,IX,IY
	PUSH	IX
	POP	HL
	LD	A,(IY+0)
	OR	A
	JR	Z,.DELETE
	PUSH	IY
	POP	DE
	INC	DE
	JR	.SET
.DELETE
	LD	DE,0
.SET
	CALL	SET_ONE
	POP	IY,IX,BC
	CALL	NEXT_NAME_IX
	LD	DE,ENV_BACKUP_SLOT
	ADD	IY,DE
	DJNZ	.LOOP
	RET

; SET_ONE: HL=name, DE=value or zero for deletion.
SET_ONE
	LD	(NETENV_VALUE),DE
	LD	DE,ENV_SET_BUFFER
.NAME
	LD	A,(HL)
	OR	A
	JR	Z,.EQUALS
	LD	(DE),A
	INC	HL
	INC	DE
	JR	.NAME
.EQUALS
	LD	A,'='
	LD	(DE),A
	INC	DE
	LD	HL,(NETENV_VALUE)
	LD	A,H
	OR	L
	JR	Z,.TERM
.VALUE
	LD	A,(HL)
	OR	A
	JR	Z,.TERM
	LD	(DE),A
	INC	HL
	INC	DE
	JR	.VALUE
.TERM
	XOR	A
	LD	(DE),A
	LD	HL,ENV_SET_BUFFER
	LD	B,ENV_SET
	LD	C,DSS_ENVIRON
	RST	DSS
	RET

NEXT_NAME_IX
.LOOP
	LD	A,(IX+0)
	INC	IX
	OR	A
	JR	NZ,.LOOP
	RET

; FORMAT_IPV4: HL=4 bytes, DE=destination ASCIIZ.
FORMAT_IPV4
	PUSH	IX,IY
	LD	B,4
.OCTET
	LD	A,(HL)
	INC	HL
	CALL	FORMAT_U8
	DEC	B
	JR	Z,.DONE
	LD	A,'.'
	LD	(DE),A
	INC	DE
	JR	.OCTET
.DONE
	XOR	A
	LD	(DE),A
	POP	IY,IX
	RET

; FORMAT_MAC: HL=6 bytes, DE=destination.
FORMAT_MAC
	PUSH	IX,IY
	LD	B,6
.BYTE
	LD	A,(HL)
	INC	HL
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	FORMAT_NIBBLE
	POP	AF
	CALL	FORMAT_NIBBLE
	DEC	B
	JR	Z,.DONE
	LD	A,':'
	LD	(DE),A
	INC	DE
	JR	.BYTE
.DONE
	XOR	A
	LD	(DE),A
	POP	IY,IX
	RET

FORMAT_NIBBLE
	AND	0x0F
	ADD	A,'0'
	CP	'9'+1
	JR	C,.STORE
	ADD	A,'A'-'9'-1
.STORE
	LD	(DE),A
	INC	DE
	RET

FORMAT_U8
	LD	C,A
	LD	A,0
	LD	(NETENV_STARTED),A
	LD	A,C
	LD	C,0
.HUNDRED
	CP	100
	JR	C,.TENS
	SUB	100
	INC	C
	JR	.HUNDRED
.TENS
	LD	(NETENV_REMAINDER),A
	LD	A,C
	OR	A
	JR	Z,.NO_HUNDRED
	ADD	A,'0'
	LD	(DE),A
	INC	DE
	LD	A,1
	LD	(NETENV_STARTED),A
.NO_HUNDRED
	LD	A,(NETENV_REMAINDER)
	LD	C,0
.TEN_LOOP
	CP	10
	JR	C,.ONES
	SUB	10
	INC	C
	JR	.TEN_LOOP
.ONES
	LD	(NETENV_REMAINDER),A
	LD	A,(NETENV_STARTED)
	OR	C
	JR	Z,.ONLY_ONE
	LD	A,C
	ADD	A,'0'
	LD	(DE),A
	INC	DE
.ONLY_ONE
	LD	A,(NETENV_REMAINDER)
	ADD	A,'0'
	LD	(DE),A
	INC	DE
	RET

; FORMAT_U32 converts little-endian 32-bit to decimal by repeated division.
; In: HL=4-byte value, DE=destination. Uses 16-byte scratch in resident BSS.
FORMAT_U32
	PUSH	IX,IY
	LD	IX,NETCFG_SCRATCH
	LD	B,4
.COPY
	LD	A,(HL)
	LD	(IX+0),A
	INC	HL
	INC	IX
	DJNZ	.COPY
	LD	IY,NETCFG_SCRATCH+4
	LD	B,0			; digit count
.DIVIDE
	LD	HL,NETCFG_SCRATCH
	LD	A,(HL)
	INC	HL
	OR	(HL)
	INC	HL
	OR	(HL)
	INC	HL
	OR	(HL)
	JR	Z,.OUTPUT
	LD	IX,NETCFG_SCRATCH+3
	LD	C,4
	LD	A,0			; remainder
.BYTE_DIV
	LD	H,A
	LD	L,(IX+0)
	PUSH	BC,DE
	LD	BC,0			; quotient byte
	LD	DE,10
.SUB10
	OR	A
	SBC	HL,DE
	JR	C,.BYTE_DONE
	INC	C
	JR	.SUB10
.BYTE_DONE
	ADD	HL,DE
	LD	A,C
	LD	(IX+0),A
	LD	A,L			; remainder for next less-significant byte
	POP	DE,BC
	DEC	IX
	DEC	C
	JR	NZ,.BYTE_DIV
	ADD	A,'0'
	LD	(IY+0),A
	INC	IY
	INC	B
	JR	.DIVIDE
.OUTPUT
	LD	A,B
	OR	A
	JR	NZ,.REVERSE
	LD	A,'0'
	LD	(DE),A
	INC	DE
	JR	.TERM
.REVERSE
	DEC	IY
	LD	A,(IY+0)
	LD	(DE),A
	INC	DE
	DJNZ	.REVERSE
.TERM
	XOR	A
	LD	(DE),A
	POP	IY,IX
	RET

FORMAT_U16
	LD	B,0
.DIV
	LD	A,H
	OR	L
	JR	Z,.OUT
	CALL	DIV10
	ADD	A,'0'
	PUSH	AF
	INC	B
	JR	.DIV
.OUT
	LD	A,B
	OR	A
	JR	NZ,.POP
	LD	A,'0'
	LD	(DE),A
	INC	DE
	RET
.POP
	POP	AF
	LD	(DE),A
	INC	DE
	DJNZ	.POP
	RET

DIV10
	LD	BC,0
.LOOP
	LD	A,H
	OR	A
	JR	NZ,.SUB
	LD	A,L
	CP	10
	JR	C,.DONE
.SUB
	LD	A,L
	SUB	10
	LD	L,A
	JR	NC,.INC
	DEC	H
.INC
	INC	BC
	JR	.LOOP
.DONE
	LD	A,L
	LD	H,B
	LD	L,C
	RET

; Public ordered names; desired pointer tables use this exact order.
ENV_NAMES
	DB "NET",0,"NET_HW",0,"NET_IDPORT",0,"NET_MAC",0
	DB "NET_IP_SRC",0,"NET_IP",0,"NET_MASK",0,"NET_GW",0
	DB "NET_DNS1",0,"NET_DNS2",0,"NET_NTP",0,"NET_TZ",0
	DB "NET_DHCP_SRV",0,"NET_LEASE_SEC",0

N_NET		EQU ENV_NAMES
N_NET_HW	EQU ENV_NAMES+4
N_NET_IDPORT	EQU ENV_NAMES+11
N_NET_MAC	EQU ENV_NAMES+22

NETENV_EMPTY_DESIRED	DS ENV_VAR_COUNT*2,0
NETENV_DESIRED	DW 0
NETENV_VALUE	DW 0
NETENV_SAVED_ERROR	DB 0
NETENV_STARTED	DB 0
NETENV_REMAINDER	DB 0

	ENDMODULE
	ENDIF
