	JP	C,.T_BAD
	LD	A,(S9_TFTP_MODE)
	OR	A
	JR	NZ,.OVERRIDE_REMOTE
	LD	DE,S9_TFTP_LOCAL_NAME
	LD	C,96
	JR	.OVERRIDE_COPY
.OVERRIDE_REMOTE
	LD	DE,S9_TFTP_REMOTE_NAME
	LD	C,80
.OVERRIDE_COPY
