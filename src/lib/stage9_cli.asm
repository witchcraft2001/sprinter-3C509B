	JR	Z,.W_OUTPUT
	CP	'Y'
	JR	Z,.W_FORCE
	CP	'F'
	JR	Z,.W_FORCE
	CP	'R'
	JR	Z,.W_RESUME
	CP	'D'
	JR	NZ,.W_BAD
	LD	B,0x04
	JR	.W_MARK
.W_FORCE
	LD	B,0x01
	JR	.W_MARK
.W_RESUME
	LD	B,0x02
