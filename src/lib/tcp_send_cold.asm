; Pure DLL SEND state transitions. No NIC, DSS, hot address or suspended stack.
; All SEND entries: IX=context, IY=S11_STATE_BASE; preserve IX/IY.
; Mutable words are addressed through IY so WIN1/WIN2 relocation is identical.
; SPDX-License-Identifier: BSD-3-Clause
	INCLUDE "tcp.inc"

	MACRO SEND_LOAD lo, hi, field
	LD	lo,(IY+field-S11_STATE_BASE)
	LD	hi,(IY+field-S11_STATE_BASE+1)
	ENDM
	MACRO SEND_STORE lo, hi, field
	LD	(IY+field-S11_STATE_BASE),lo
	LD	(IY+field-S11_STATE_BASE+1),hi
	ENDM

; BEGIN: BC=SENDSLICE. Async calls share one slice across all transitions.
; Blocking calls are bounded by unanswered attempts, never total progress.
; Out A=0/CF=0. Clobbers AF/BC.
SEND_BEGIN
	LD	A,B
	OR	C
	LD	(IY+S11_SEND_BLOCKING-S11_STATE_BASE),0
	JR	NZ,.READY
	INC	(IY+S11_SEND_BLOCKING-S11_STATE_BASE)
	LD	BC,0xFFFF
.READY
	SEND_STORE C,B,S11_SEND_CALL_LEFT
	XOR	A
	RET

; STEP: Out A=0 done, 1 transmit data, 2 wait (BC=budget), 3 probe;
; CF=1/A=TCP_ERR_* terminal or AGAIN. DE=confirmed prefix on done.
; Phase 0 prepares a segment, 1/3 transmit once, 2/4 wait for ACK/window.
; Clobbers AF/BC/DE/HL.
SEND_STEP
	SEND_LOAD L,H,S11_SEND_REMAINING
	LD	A,H
	OR	L
	JR	NZ,.PENDING
	SEND_LOAD E,D,S11_SEND_CONFIRMED
	RET
.PENDING
	LD	A,(IY+S11_SEND_PHASE-S11_STATE_BASE)
	CP	DLL_SEND_ACK
	JR	Z,.CHECK_INTERVAL
	CP	DLL_SEND_WINDOW
	JR	NZ,.CHECK_CALL
.CHECK_INTERVAL
	SEND_LOAD L,H,S11_ASYNC_MS_LEFT
	LD	A,H
	OR	L
	JR	NZ,.CHECK_CALL
	CALL	SEND_EXPIRED
	RET	C
.CHECK_CALL
	LD	A,(IY+S11_SEND_BLOCKING-S11_STATE_BASE)
	OR	A
	LD	HL,0xFFFF
	JR	NZ,.DISPATCH
	SEND_LOAD L,H,S11_SEND_CALL_LEFT
	LD	A,H
	OR	L
	JR	NZ,.DISPATCH
	LD	A,TCP_ERR_AGAIN
	JR	SEND_STATUS
.DISPATCH
	LD	A,(IY+S11_SEND_PHASE-S11_STATE_BASE)
	OR	A
	JP	Z,SEND_PREPARE
	CP	DLL_SEND_DATA
	JR	Z,.DATA
	CP	DLL_SEND_PROBE
	JR	Z,.PROBE
	SEND_LOAD E,D,S11_ASYNC_MS_LEFT
	; HL=call budget, DE=attempt budget: preserve the operands of min().
	OR	A
	SBC	HL,DE
	ADD	HL,DE
	JR	C,.WAIT
	EX	DE,HL
.WAIT
	LD	B,H
	LD	C,L
	LD	A,DLL_SEND_ACK
	OR	A
	RET
.DATA
	LD	HL,DLL_SEND_WAIT_MS
	LD	A,(IX+CTX_RETRY_LEFT)
	CP	DLL_SEND_ATTEMPTS
	JR	Z,.DATA_READY
	ADD	HL,HL
	CP	DLL_SEND_ATTEMPTS-1
	JR	Z,.DATA_READY
	ADD	HL,HL
.DATA_READY
	LD	A,DLL_SEND_DATA
	JR	.TRANSMIT
.PROBE
	SEND_LOAD L,H,S11_PROBE_INTERVAL
	LD	(IY+S11_PROBE_ANSWERED-S11_STATE_BASE),0
	LD	A,DLL_SEND_PROBE
.TRANSMIT
	SEND_STORE L,H,S11_ASYNC_MS_LEFT
	INC	(IY+S11_SEND_PHASE-S11_STATE_BASE)
	RES	0,(IX+CTX_EVENT)
	RES	2,(IX+CTX_EVENT)
	RES	3,(IX+CTX_EVENT)
	RES	5,(IX+CTX_EVENT)
	OR	A
	RET
SEND_STATUS
	SCF
	RET

SEND_PREPARE
	LD	E,(IX+CTX_REMOTE_WINDOW)
	LD	D,(IX+CTX_REMOTE_WINDOW+1)
	LD	A,D
	OR	E
	JR	NZ,.SEGMENT
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),DLL_SEND_PROBE
	LD	(IY+S11_DIAG_STAGE-S11_STATE_BASE),TCP_STAGE_WINDOW
	LD	HL,DLL_SEND_WAIT_MS
	SEND_STORE L,H,S11_PROBE_INTERVAL
	LD	(IY+S11_PROBE_MISSED-S11_STATE_BASE),0
	JP	SEND_STEP
.SEGMENT
	LD	(IY+S11_DIAG_STAGE-S11_STATE_BASE),TCP_STAGE_DATA
	SEND_LOAD L,H,S11_SEND_REMAINING
	CALL	SEND_MIN
	LD	E,(IX+CTX_PEER_MSS)
	LD	D,(IX+CTX_PEER_MSS+1)
	LD	A,D
	OR	E
	JR	Z,.MSS
	CALL	SEND_MIN
.MSS
	LD	DE,TCP_MSS
	CALL	SEND_MIN
	SEND_STORE L,H,S11_ACTIVE_LENGTH
	EX	DE,HL
	; Advance SND.NXT and save the target in network order, including wrap.
	LD	A,(IX+CTX_SND_NXT+3)
	ADD	A,E
	LD	(IX+CTX_SND_NXT+3),A
	LD	(IY+S11_TARGET_ACK-S11_STATE_BASE+3),A
	LD	A,(IX+CTX_SND_NXT+2)
	ADC	A,D
	LD	(IX+CTX_SND_NXT+2),A
	LD	(IY+S11_TARGET_ACK-S11_STATE_BASE+2),A
	LD	A,(IX+CTX_SND_NXT+1)
	ADC	A,0
	LD	(IX+CTX_SND_NXT+1),A
	LD	(IY+S11_TARGET_ACK-S11_STATE_BASE+1),A
	LD	A,(IX+CTX_SND_NXT)
	ADC	A,0
	LD	(IX+CTX_SND_NXT),A
	LD	(IY+S11_TARGET_ACK-S11_STATE_BASE),A
	LD	(IX+CTX_RETRY_LEFT),DLL_SEND_ATTEMPTS
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),DLL_SEND_DATA
	JP	SEND_STEP

; HL=min(HL,DE). Clobbers flags, preserves DE.
SEND_MIN
	OR	A
	SBC	HL,DE
	ADD	HL,DE
	RET	C
	LD	H,D
	LD	L,E
	RET

; CHARGE: DE=elapsed NETTIME quanta. Charge the attempt and, in async mode,
; the public call budget. Blocking calls have no total transfer deadline.
; A packet with zero elapsed ticks costs one unit, bounding ACK floods.
; Out CF=0. Clobbers AF/DE/HL.
SEND_CHARGE
	LD	A,D
	OR	E
	JR	NZ,.NONZERO
	INC	DE
.NONZERO
	SEND_LOAD L,H,S11_ASYNC_MS_LEFT
	CALL	.SAT_SUB
	SEND_STORE L,H,S11_ASYNC_MS_LEFT
	LD	A,(IY+S11_SEND_BLOCKING-S11_STATE_BASE)
	OR	A
	RET	NZ
	SEND_LOAD L,H,S11_SEND_CALL_LEFT
	CALL	.SAT_SUB
	SEND_STORE L,H,S11_SEND_CALL_LEFT
	XOR	A
	RET
.SAT_SUB
	OR	A
	SBC	HL,DE
	RET	NC
	LD	HL,0
	RET

; RESULT: E=event bits or TCP_ERR_TIMEOUT. Out CF/status; CF=0 continues.
; The receive dispatcher has already consumed the event bits.
SEND_RESULT
	LD	A,E
	CP	TCP_ERR_TIMEOUT
	RET	Z			; STEP handles a depleted interval exactly once
	BIT	3,E
	LD	A,TCP_ERR_RESET
	JP	NZ,SEND_STATUS
	LD	A,(IY+S11_SEND_PHASE-S11_STATE_BASE)
	CP	DLL_SEND_WINDOW
	JR	Z,.WINDOW
	CALL	TCP_SEND_EVENT
	JR	NC,.DATA
	; FIN's classifier includes any ACKed prefix of the last segment.
	SEND_STORE E,D,S11_SEND_CONFIRMED
	RET
.DATA
	OR	A
	RET	NZ			; a non-terminal ACK must not restart a deadline
	SEND_LOAD E,D,S11_ACTIVE_LENGTH
	SEND_LOAD L,H,S11_SEND_POINTER
	ADD	HL,DE
	SEND_STORE L,H,S11_SEND_POINTER
	SEND_LOAD L,H,S11_SEND_CONFIRMED
	ADD	HL,DE
	SEND_STORE L,H,S11_SEND_CONFIRMED
	SEND_LOAD L,H,S11_SEND_REMAINING
	OR	A
	SBC	HL,DE
	SEND_STORE L,H,S11_SEND_REMAINING
	XOR	A
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),A
	LD	(IY+S11_ACTIVE_LENGTH-S11_STATE_BASE),A
	LD	(IY+S11_ACTIVE_LENGTH-S11_STATE_BASE+1),A
	RET
.WINDOW
	BIT	0,E
	JR	Z,.WINDOW_FIN
	LD	(IY+S11_PROBE_MISSED-S11_STATE_BASE),0
	LD	(IY+S11_PROBE_ANSWERED-S11_STATE_BASE),1
.WINDOW_FIN
	; A FIN closes only the peer's sending direction. Continue our stream
	; in CLOSE_WAIT, including an ACK+FIN that reopens its receive window.
	LD	A,(IX+CTX_REMOTE_WINDOW)
	OR	(IX+CTX_REMOTE_WINDOW+1)
	RET	Z			; reply at win=0 leaves interval and call budget intact
	XOR	A
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),A
	RET

SEND_EXPIRED
	LD	A,(IY+S11_SEND_PHASE-S11_STATE_BASE)
	CP	DLL_SEND_WINDOW
	JR	Z,.WINDOW
	DEC	(IX+CTX_RETRY_LEFT)
	LD	A,TCP_ERR_TIMEOUT
	JP	Z,SEND_STATUS
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),DLL_SEND_DATA
	XOR	A
	RET
.WINDOW
	LD	A,(IY+S11_PROBE_ANSWERED-S11_STATE_BASE)
	OR	A
	JR	NZ,.INTERVAL
	INC	(IY+S11_PROBE_MISSED-S11_STATE_BASE)
	LD	A,(IY+S11_PROBE_MISSED-S11_STATE_BASE)
	CP	DLL_SEND_ATTEMPTS
	LD	A,TCP_ERR_WINDOW
	JP	Z,SEND_STATUS
.INTERVAL
	SEND_LOAD L,H,S11_PROBE_INTERVAL
	ADD	HL,HL
	LD	DE,DLL_PROBE_MAX_MS
	CALL	SEND_MIN
	SEND_STORE L,H,S11_PROBE_INTERVAL
.READY
	LD	(IY+S11_SEND_PHASE-S11_STATE_BASE),DLL_SEND_PROBE
	XOR	A
	RET

; TCP_ACK_SEQUENCE: IX=context, IY=state. CF=0 for a sequence within the
; advertised receive window, including an out-of-order segment past a hole.
; ACK at RCV.NXT is usable even at zero window, independently of data/FIN.
; Payload acceptance remains the receive dispatcher's job. Clobbers AF/BC/DE/HL.
; The receive-window calculation mirrors TCP_IP_BUILD's durable/direct scope.
TCP_ACK_SEQUENCE
	LD	A,(IY+S11_PARSE_SEQUENCE-S11_STATE_BASE+3)
	SUB	(IX+CTX_RCV_NXT+3)
	LD	E,A
	LD	A,(IY+S11_PARSE_SEQUENCE-S11_STATE_BASE+2)
	SBC	A,(IX+CTX_RCV_NXT+2)
	LD	D,A
	LD	A,(IY+S11_PARSE_SEQUENCE-S11_STATE_BASE+1)
	SBC	A,(IX+CTX_RCV_NXT+1)
	LD	C,A
	LD	A,(IY+S11_PARSE_SEQUENCE-S11_STATE_BASE)
	SBC	A,(IX+CTX_RCV_NXT)
	LD	B,A
	OR	C
	JR	Z,.NONNEGATIVE
	LD	A,B
	AND	C
	CP	0xFF
	JP	NZ,.REJECT
	BIT	7,D
	JP	Z,.REJECT
	; A retransmitted segment can start before RCV.NXT but overlap it.
	SEND_LOAD L,H,S11_TCP_PARSE_DESC+TCPP_PAYLOAD_LENGTH
	LD	A,(IY+S11_TCP_PARSE_DESC-S11_STATE_BASE+TCPP_FLAGS)
	AND	TCP_FLAG_FIN
	JR	Z,.OVERLAP_LENGTH
	INC	HL
.OVERLAP_LENGTH
	ADD	HL,DE
	JP	NC,.REJECT
	LD	A,H
	OR	L
	JP	Z,.REJECT
	LD	DE,0
	JR	.WINDOW_REQUIRED
.NONNEGATIVE
	LD	A,D
	OR	E
	RET	Z
.WINDOW_REQUIRED
	LD	A,(IX+CTX_REMOTE_FIN)
	OR	A
	JP	NZ,.REJECT
	PUSH	DE
	LD	HL,TCP_MSS
	LD	E,(IX+CTX_PENDING_OFF)
	LD	D,(IX+CTX_PENDING_OFF+1)
	OR	A
	SBC	HL,DE
	LD	E,(IX+CTX_PENDING_LEN)
	LD	D,(IX+CTX_PENDING_LEN+1)
	SBC	HL,DE
	LD	A,(IY+S11_SELECTED_CONTEXT-S11_STATE_BASE)
	CP	IXL
	JR	NZ,.WINDOW
	LD	A,(IY+S11_SELECTED_CONTEXT-S11_STATE_BASE+1)
	CP	IXH
	JR	NZ,.WINDOW
	LD	A,(IY+S11_RX_DEST-S11_STATE_BASE+1)
	AND	0xC0
	JR	Z,.WINDOW
	LD	A,(IY+S11_RX_FREE-S11_STATE_BASE)
	OR	(IY+S11_RX_FREE-S11_STATE_BASE+1)
	JR	Z,.WINDOW
	PUSH	HL
	SEND_LOAD L,H,S11_RX_FREE
	SEND_LOAD E,D,S11_RX_DELIVERED
	OR	A
	SBC	HL,DE
	POP	DE
	ADD	HL,DE
.WINDOW
	LD	DE,TCP_RECV_MAX_WINDOW
	OR	A
	SBC	HL,DE
	JR	NC,.MAX_WINDOW
	ADD	HL,DE
	PUSH	HL
	LD	DE,TCP_MSS
.ROUND
	OR	A
	SBC	HL,DE
	JR	NC,.ROUND
	ADD	HL,DE
	EX	DE,HL
	POP	HL
	OR	A
	SBC	HL,DE
	JR	.CHECK
.MAX_WINDOW
	LD	HL,TCP_RECV_MAX_WINDOW
.CHECK
	POP	DE
	OR	A
	SBC	HL,DE
	JR	Z,.REJECT
	RET
.REJECT
	SCF
	RET

; Buffered-only RECV while SEND is suspended.
; IX=COLD_CTX, IY=&UNET_ARG_A; caller validated channel and buffer.
; Out CF/raw TCP status, BC=bytes, HL=source, DE=caller destination.
; The hot shim copies only after unmapping this overlay (destination may be WIN0).
; Clobbers AF/DE/HL/IX/IY.
; Does not touch any SEND/parse/wait state or read/transmit a frame.
RECV_BUFFERED
	LD	E,(IX+CCTX_TCP_CONTEXT0)
	LD	D,(IX+CCTX_TCP_CONTEXT0+1)
	LD	L,(IX+CCTX_TCP_PENDING0)
	LD	H,(IX+CCTX_TCP_PENDING0+1)
	LD	A,(IY)
	OR	A
	JR	Z,.SELECTED
	LD	BC,TCP_MSS
	ADD	HL,BC
	EX	DE,HL
	LD	BC,40
	ADD	HL,BC
	EX	DE,HL
.SELECTED
	PUSH	DE
	POP	IX
	LD	C,(IY+3)		; UNET_ARG_IX: capacity
	LD	B,(IY+4)
	LD	E,(IX+CTX_PENDING_LEN)
	LD	D,(IX+CTX_PENDING_LEN+1)
	LD	A,D
	OR	E
	JR	Z,.EMPTY
	PUSH	HL
	LD	H,B
	LD	L,C
	CALL	SEND_MIN
	LD	B,H
	LD	C,L
	EX	DE,HL
	OR	A
	SBC	HL,BC
	LD	(IX+CTX_PENDING_LEN),L
	LD	(IX+CTX_PENDING_LEN+1),H
	LD	E,(IX+CTX_PENDING_OFF)
	LD	D,(IX+CTX_PENDING_OFF+1)
	LD	A,H
	OR	L
	JR	Z,.DRAINED
	LD	H,D
	LD	L,E
	ADD	HL,BC
.DRAINED
	LD	(IX+CTX_PENDING_OFF),L
	LD	(IX+CTX_PENDING_OFF+1),H
	SET	1,(IX+CTX_WINDOW_CLOSED) ; deferred ACK, sent by SEND or ordinary RECV
	POP	HL
	ADD	HL,DE
	LD	E,(IY+1)
	LD	D,(IY+2)
	XOR	A
	RET
.EMPTY
	LD	BC,0
	; Defer EOF until SEND completes: the shim releases/re-arms on CLOSED.
	; Neither channel may lose its context while a continuation owns it.
	XOR	A
	RET
