	IFNDEF	_CLI_STAGE6_ASM
	DEFINE	_CLI_STAGE6_ASM

	INCLUDE "el3.inc"
	INCLUDE "memory.inc"

	MODULE CLI6

MODE_TX		EQU 0
MODE_RX		EQU 1

SEEN_VERBOSE	EQU 0x01
SEEN_SLOT	EQU 0x02
SEEN_IDPORT	EQU 0x04
SEEN_BASE	EQU 0x08
SEEN_COUNT	EQU 0x10
SEEN_WAIT	EQU 0x20
SEEN_DEST	EQU 0x40
SEEN_TYPE	EQU 0x80
SEEN_LENGTH	EQU 0x01
SEEN_PATTERN	EQU 0x02
SEEN_HEXDUMP	EQU 0x04

PATTERN_00	EQU 0
PATTERN_FF	EQU 1
PATTERN_55	EQU 2
PATTERN_AA	EQU 3
PATTERN_INC	EQU 4

; PARSE_TX / PARSE_RX
; In: CMDLINE_SOURCE points to a DSS length-prefixed command line.
; Out: parsed CLI_* fields and CF=0, or stable error/CF=1.
; Preserves IX and IY.
PARSE_TX
	PUSH	IX,IY
	XOR	A
	CALL	PARSE_MODE
	POP	IY,IX
	RET

PARSE_RX
	PUSH	IX,IY
	LD	A,MODE_RX
	CALL	PARSE_MODE
	POP	IY,IX
	RET

PARSE_MODE
	LD	(PARSER_MODE),A
	XOR	A
	LD	(SEEN_LOW),A
	LD	(SEEN_HIGH),A
	LD	(CLI_VERBOSE),A
	LD	(CLI_HEXDUMP),A
	LD	(CLI_PATTERN),A
	LD	A,1
	LD	(CLI_BASE_AUTO),A
	LD	(CLI_SLOT),A
	LD	HL,EL3_IDPORT_DEFAULT
	LD	(CLI_IDPORT),HL
	LD	HL,1
	LD	(CLI_COUNT),HL
	LD	HL,10000
	LD	(CLI_WAIT),HL
	LD	HL,0x88B5
	LD	(CLI_ETHERTYPE),HL
	LD	HL,60
	LD	(CLI_LENGTH),HL
	LD	A,PATTERN_INC
	LD	(CLI_PATTERN),A
	CALL	READER_INIT
.TOKEN_LOOP
	CALL	NEXT_TOKEN
	JP	C,.END_ARGS
	LD	A,(CLI_TOKEN_LEN)
	CP	2
	JP	NZ,PARAM_ERROR
	LD	A,(HL)
	CP	'-'
	JR	Z,.PREFIX_OK
	CP	'/'
	JP	NZ,PARAM_ERROR
.PREFIX_OK
	INC	HL
	LD	A,(HL)
	CALL	TO_LOWER
	CP	'?'
	JP	Z,HELP_RESULT
	CP	'h'
	JP	Z,HELP_RESULT
	CP	'v'
	JP	Z,.VERBOSE
	CP	'x'
	JP	Z,.HEXDUMP
	CP	's'
	JP	Z,.SLOT
	CP	'p'
	JP	Z,.IDPORT
	CP	'b'
	JP	Z,.BASE
	CP	'n'
	JP	Z,.COUNT
	CP	'w'
	JP	Z,.WAIT
	CP	'd'
	JP	Z,.DEST
	CP	't'
	JP	Z,.TYPE
	CP	'l'
	JP	Z,.LENGTH
	CP	'f'
	JP	Z,.PATTERN
	JP	PARAM_ERROR

.VERBOSE
	LD	A,SEEN_VERBOSE
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	LD	A,1
	LD	(CLI_VERBOSE),A
	JP	.TOKEN_LOOP

.HEXDUMP
	LD	A,(PARSER_MODE)
	CP	MODE_RX
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_HEXDUMP
	CALL	MARK_HIGH
	JP	C,PARAM_ERROR
	LD	A,1
	LD	(CLI_HEXDUMP),A
	JP	.TOKEN_LOOP

.SLOT
	LD	A,SEEN_SLOT
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	1
	JP	NZ,PARAM_ERROR
	LD	A,(HL)
	CP	'0'
	JR	Z,.SLOT_ZERO
	CP	'1'
	JP	NZ,PARAM_ERROR
	LD	A,1
	JR	.SLOT_STORE
.SLOT_ZERO
	XOR	A
.SLOT_STORE
	LD	(CLI_SLOT),A
	JP	.TOKEN_LOOP

.IDPORT
	LD	A,SEEN_IDPORT
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	A,B
	CP	0x01
	JP	NZ,PARAM_ERROR
	LD	A,C
	AND	0x0F
	JP	NZ,PARAM_ERROR
	LD	A,C
	CP	0xF1
	JP	NC,PARAM_ERROR
	LD	(CLI_IDPORT),BC
	JP	.TOKEN_LOOP

.BASE
	LD	A,SEEN_BASE
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	IS_AUTO_TOKEN
	JR	NC,.BASE_AUTO
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	H,B
	LD	L,C
	CALL	@EL3ALG.BASE_ENCODE
	JP	C,PARAM_ERROR
	LD	(CLI_BASE),HL
	XOR	A
	LD	(CLI_BASE_AUTO),A
	JP	.TOKEN_LOOP
.BASE_AUTO
	LD	A,1
	LD	(CLI_BASE_AUTO),A
	JP	.TOKEN_LOOP

.COUNT
	LD	A,SEEN_COUNT
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	PARSE_DECIMAL
	JP	C,PARAM_ERROR
	LD	A,B
	OR	A
	JP	NZ,PARAM_ERROR
	LD	A,C
	OR	A
	JP	Z,PARAM_ERROR
	CP	101
	JP	NC,PARAM_ERROR
	LD	(CLI_COUNT),BC
	JP	.TOKEN_LOOP

.WAIT
	LD	A,SEEN_WAIT
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	PARSE_DECIMAL
	JP	C,PARAM_ERROR
	LD	A,B
	OR	C
	JP	Z,PARAM_ERROR
	LD	HL,10000
	OR	A
	SBC	HL,BC
	JP	C,PARAM_ERROR
	LD	(CLI_WAIT),BC
	JP	.TOKEN_LOOP

.DEST
	LD	A,(PARSER_MODE)
	CP	MODE_TX
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_DEST
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	PARSE_MAC
	JP	C,PARAM_ERROR
	JP	.TOKEN_LOOP

.TYPE
	LD	A,(PARSER_MODE)
	CP	MODE_TX
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_TYPE
	CALL	MARK_LOW
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	5
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	A,B
	CP	0x06
	JP	C,PARAM_ERROR
	LD	(CLI_ETHERTYPE),BC
	JP	.TOKEN_LOOP

.LENGTH
	LD	A,(PARSER_MODE)
	CP	MODE_TX
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_LENGTH
	CALL	MARK_HIGH
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	PARSE_DECIMAL
	JP	C,PARAM_ERROR
	LD	HL,BC
	LD	DE,14
	OR	A
	SBC	HL,DE
	JP	C,PARAM_ERROR
	LD	HL,1514
	OR	A
	SBC	HL,BC
	JP	C,PARAM_ERROR
	LD	(CLI_LENGTH),BC
	JP	.TOKEN_LOOP

.PATTERN
	LD	A,(PARSER_MODE)
	CP	MODE_TX
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_PATTERN
	CALL	MARK_HIGH
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	CALL	PARSE_PATTERN
	JP	C,PARAM_ERROR
	LD	(CLI_PATTERN),A
	JP	.TOKEN_LOOP

.END_ARGS
	LD	A,(PARSER_MODE)
	CP	MODE_RX
	JR	Z,.SUCCESS
	LD	A,(SEEN_LOW)
	AND	SEEN_DEST
	JR	Z,PARAM_ERROR
.SUCCESS
	XOR	A
	RET

HELP_RESULT
	LD	A,EL3_CLI_HELP
	SCF
	RET

PARAM_ERROR
	LD	A,EL3_ERR_PARAMETER
	SCF
	RET

READER_INIT
	LD	HL,(CMDLINE_SOURCE)
	LD	A,(HL)
	INC	HL
	LD	(CLI_READER_PTR),HL
	LD	(CLI_READER_REMAIN),A
	RET

NEXT_TOKEN
	LD	HL,(CLI_READER_PTR)
	LD	A,(CLI_READER_REMAIN)
	LD	B,A
.SKIP
	LD	A,B
	OR	A
	JR	Z,.NONE
	LD	A,(HL)
	CP	' '
	JR	Z,.SKIP_ONE
	CP	9
	JR	NZ,.START
.SKIP_ONE
	INC	HL
	DEC	B
	JR	.SKIP
.START
	PUSH	HL
	LD	C,0
.SCAN
	LD	A,B
	OR	A
	JR	Z,.DONE
	LD	A,(HL)
	CP	' '
	JR	Z,.DONE
	CP	9
	JR	Z,.DONE
	INC	HL
	INC	C
	DEC	B
	JR	.SCAN
.DONE
	LD	(CLI_READER_PTR),HL
	LD	A,B
	LD	(CLI_READER_REMAIN),A
	LD	A,C
	LD	(CLI_TOKEN_LEN),A
	POP	HL
	OR	A
	RET
.NONE
	LD	(CLI_READER_PTR),HL
	XOR	A
	LD	(CLI_READER_REMAIN),A
	SCF
	RET

MARK_LOW
	LD	B,A
	LD	A,(SEEN_LOW)
	AND	B
	JR	NZ,.DUP_LOW
	LD	A,(SEEN_LOW)
	OR	B
	LD	(SEEN_LOW),A
	OR	A
	RET
.DUP_LOW
	SCF
	RET

MARK_HIGH
	LD	B,A
	LD	A,(SEEN_HIGH)
	AND	B
	JR	NZ,.DUP_HIGH
	LD	A,(SEEN_HIGH)
	OR	B
	LD	(SEEN_HIGH),A
	OR	A
	RET
.DUP_HIGH
	SCF
	RET

TO_LOWER
	CP	'A'
	RET	C
	CP	'Z'+1
	RET	NC
	ADD	A,'a'-'A'
	RET

IS_AUTO_TOKEN
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JR	NZ,.NO_AUTO
	LD	DE,AUTO_TEXT
	LD	B,4
.AUTO_LOOP
	LD	A,(HL)
	CALL	TO_LOWER
	LD	C,A
	LD	A,(DE)
	CP	C
	JR	NZ,.NO_AUTO
	INC	HL
	INC	DE
	DJNZ	.AUTO_LOOP
	OR	A
	RET
.NO_AUTO
	SCF
	RET

; Hash-prefixed 3- or 4-digit hexadecimal number.
PARSE_HASH_HEX
	LD	A,(HL)
	CP	'#'
	JR	NZ,.HEX_BAD
	INC	HL
	LD	A,(CLI_TOKEN_LEN)
	DEC	A
	LD	B,A
	LD	DE,0
.HEX_DIGIT
	LD	A,(HL)
	CALL	HEX_NIBBLE
	JR	C,.HEX_BAD
	LD	C,A
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	LD	A,E
	OR	C
	LD	E,A
	INC	HL
	DJNZ	.HEX_DIGIT
	LD	B,D
	LD	C,E
	OR	A
	RET
.HEX_BAD
	SCF
	RET

HEX_NIBBLE
	CP	'0'
	JR	C,.NIBBLE_BAD
	CP	'9'+1
	JR	C,.NIBBLE_DEC
	CALL	TO_LOWER
	CP	'a'
	JR	C,.NIBBLE_BAD
	CP	'f'+1
	JR	NC,.NIBBLE_BAD
	SUB	'a'-10
	OR	A
	RET
.NIBBLE_DEC
	SUB	'0'
	OR	A
	RET
.NIBBLE_BAD
	SCF
	RET

; Unsigned decimal 0..65535. Empty, non-decimal and overflow are rejected.
PARSE_DECIMAL
	LD	A,(CLI_TOKEN_LEN)
	OR	A
	JR	Z,.DEC_BAD
	CP	6
	JR	NC,.DEC_BAD
	LD	(PARSE_REMAIN),A
	LD	BC,0
.DEC_LOOP
	LD	A,(HL)
	CP	'0'
	JR	C,.DEC_BAD
	CP	'9'+1
	JR	NC,.DEC_BAD
	SUB	'0'
	LD	(PARSE_DIGIT),A
	PUSH	HL
	LD	H,B
	LD	L,C
	ADD	HL,HL
	JR	C,.DEC_OVERFLOW
	LD	D,H
	LD	E,L
	ADD	HL,HL
	JR	C,.DEC_OVERFLOW
	ADD	HL,HL
	JR	C,.DEC_OVERFLOW
	ADD	HL,DE
	JR	C,.DEC_OVERFLOW
	LD	A,(PARSE_DIGIT)
	LD	E,A
	LD	D,0
	ADD	HL,DE
	JR	C,.DEC_OVERFLOW
	LD	B,H
	LD	C,L
	POP	HL
	INC	HL
	LD	A,(PARSE_REMAIN)
	DEC	A
	LD	(PARSE_REMAIN),A
	JR	NZ,.DEC_LOOP
	OR	A
	RET
.DEC_OVERFLOW
	POP	HL
.DEC_BAD
	SCF
	RET

PARSE_MAC
	LD	A,(CLI_TOKEN_LEN)
	CP	17
	JR	NZ,.MAC_BAD
	LD	DE,CLI_DEST_MAC
	LD	B,6
.MAC_BYTE
	LD	A,(HL)
	CALL	HEX_NIBBLE
	JR	C,.MAC_BAD
	RLCA
	RLCA
	RLCA
	RLCA
	LD	C,A
	INC	HL
	LD	A,(HL)
	CALL	HEX_NIBBLE
	JR	C,.MAC_BAD
	OR	C
	LD	(DE),A
	INC	DE
	INC	HL
	DEC	B
	JR	Z,.MAC_DONE
	LD	A,(HL)
	CP	':'
	JR	NZ,.MAC_BAD
	INC	HL
	JR	.MAC_BYTE
.MAC_DONE
	XOR	A
	RET
.MAC_BAD
	SCF
	RET

PARSE_PATTERN
	LD	A,(CLI_TOKEN_LEN)
	CP	3
	JR	Z,.PATTERN_INC_CHECK
	CP	2
	JR	NZ,.PATTERN_BAD
	LD	A,(HL)
	CALL	TO_LOWER
	LD	B,A
	INC	HL
	LD	A,(HL)
	CALL	TO_LOWER
	CP	B
	JR	NZ,.PATTERN_BAD
	LD	A,B
	CP	'0'
	JR	Z,.PATTERN_ZERO
	CP	'f'
	JR	Z,.PATTERN_FF_VALUE
	CP	'5'
	JR	Z,.PATTERN_55_VALUE
	CP	'a'
	JR	Z,.PATTERN_AA_VALUE
	JR	.PATTERN_BAD
.PATTERN_ZERO
	XOR	A
	RET
.PATTERN_FF_VALUE
	LD	A,PATTERN_FF
	OR	A
	RET
.PATTERN_55_VALUE
	LD	A,PATTERN_55
	OR	A
	RET
.PATTERN_AA_VALUE
	LD	A,PATTERN_AA
	OR	A
	RET
.PATTERN_INC_CHECK
	LD	DE,INC_TEXT
	LD	B,3
.INC_LOOP
	LD	A,(HL)
	CALL	TO_LOWER
	LD	C,A
	LD	A,(DE)
	CP	C
	JR	NZ,.PATTERN_BAD
	INC	HL
	INC	DE
	DJNZ	.INC_LOOP
	LD	A,PATTERN_INC
	OR	A
	RET
.PATTERN_BAD
	SCF
	RET

AUTO_TEXT	DB "auto"
INC_TEXT	DB "inc"
PARSER_MODE	DB 0
SEEN_LOW	DB 0
SEEN_HIGH	DB 0
PARSE_REMAIN	DB 0
PARSE_DIGIT	DB 0

	ENDMODULE
	ENDIF
