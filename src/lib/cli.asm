	IFNDEF	_CLI_ASM
	DEFINE	_CLI_ASM

	INCLUDE "el3.inc"
	INCLUDE "isa.inc"
	INCLUDE "memory.inc"

	MODULE CLI

MODE_INFO	EQU 0
MODE_EEP	EQU 1
MODE_PROBE	EQU 2

SEEN_SLOT	EQU 0x01
SEEN_IDPORT	EQU 0x02
SEEN_BASE	EQU 0x04
SEEN_COUNT	EQU 0x08
SEEN_VERBOSE	EQU 0x10

; PARSE_INFO / PARSE_EEP / PARSE_PROBE
; Out: A=EL3_OK/CF=0, or EL3_CLI_HELP/error with CF=1.
; Parsed values are written to CLI_* runtime fields.
; Preserve IX and IY.
PARSE_INFO
	PUSH	IX,IY
	XOR	A
	CALL	PARSE_MODE
	POP	IY,IX
	RET

PARSE_EEP
	PUSH	IX,IY
	LD	A,MODE_EEP
	CALL	PARSE_MODE
	POP	IY,IX
	RET

PARSE_PROBE
	PUSH	IX,IY
	LD	A,MODE_PROBE
	CALL	PARSE_MODE
	POP	IY,IX
	RET

PARSE_MODE
	LD	(CLI_MODE),A
	XOR	A
	LD	(CLI_SEEN),A
	LD	(CLI_VERBOSE),A
	LD	(CLI_BASE_AUTO),A
	LD	HL,EL3_IDPORT_DEFAULT
	LD	(CLI_IDPORT),HL
	LD	A,ISA_SLOT_1
	LD	(CLI_SLOT),A
	LD	A,(CLI_MODE)
	CP	MODE_INFO
	JR	NZ,.NOT_INFO
	LD	A,1
	LD	(CLI_BASE_AUTO),A
.NOT_INFO
	CALL	READER_INIT
.TOKEN_LOOP
	CALL	NEXT_TOKEN
	JP	C,.END_ARGS
	LD	A,(CLI_TOKEN_LEN)
	CP	2
	JP	NZ,PARAM_ERROR
	LD	A,(HL)
	CP	'-'
	JR	Z,.PREFIX_OK
	CP	'/'
	JP	NZ,PARAM_ERROR
.PREFIX_OK
	INC	HL
	LD	A,(HL)
	CALL	TO_LOWER
	CP	'?'
	JP	Z,HELP_RESULT
	CP	'h'
	JP	Z,HELP_RESULT
	CP	's'
	JR	Z,.SLOT
	CP	'p'
	JR	Z,.IDPORT
	CP	'b'
	JR	Z,.BASE
	CP	'n'
	JP	Z,.COUNT
	CP	'v'
	JP	Z,.VERBOSE
	JP	PARAM_ERROR

.SLOT
	LD	A,SEEN_SLOT
	CALL	MARK_UNIQUE
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	1
	JP	NZ,PARAM_ERROR
	LD	A,(HL)
	CP	'0'
	JR	Z,.SLOT_ZERO
	CP	'1'
	JP	NZ,PARAM_ERROR
	LD	A,1
	JR	.SLOT_STORE
.SLOT_ZERO
	XOR	A
.SLOT_STORE
	LD	(CLI_SLOT),A
	JP	.TOKEN_LOOP

.IDPORT
	LD	A,(CLI_MODE)
	CP	MODE_PROBE
	JP	Z,PARAM_ERROR
	LD	A,SEEN_IDPORT
	CALL	MARK_UNIQUE
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	A,B
	CP	0x01
	JP	NZ,PARAM_ERROR
	LD	A,C
	AND	0x0F
	JP	NZ,PARAM_ERROR
	LD	A,C
	CP	0xF1
	JP	NC,PARAM_ERROR
	LD	(CLI_IDPORT),BC
	JP	.TOKEN_LOOP

.BASE
	LD	A,SEEN_BASE
	CALL	MARK_UNIQUE
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_MODE)
	CP	MODE_EEP
	JP	Z,PARAM_ERROR
	CP	MODE_PROBE
	JR	Z,.PROBE_BASE
	CALL	IS_AUTO_TOKEN
	JR	NC,.AUTO_BASE
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	H,B
	LD	L,C
	CALL	@EL3ALG.BASE_ENCODE
	JP	C,PARAM_ERROR
	LD	(CLI_BASE),HL
	XOR	A
	LD	(CLI_BASE_AUTO),A
	JP	.TOKEN_LOOP
.AUTO_BASE
	LD	A,1
	LD	(CLI_BASE_AUTO),A
	JP	.TOKEN_LOOP
.PROBE_BASE
	LD	A,(CLI_TOKEN_LEN)
	CP	5
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	BIT	6,B
	JP	NZ,PARAM_ERROR
	BIT	7,B
	JP	NZ,PARAM_ERROR
	LD	(CLI_BASE),BC
	JP	.TOKEN_LOOP

.COUNT
	LD	A,(CLI_MODE)
	CP	MODE_PROBE
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_COUNT
	CALL	MARK_UNIQUE
	JP	C,PARAM_ERROR
	CALL	NEXT_TOKEN
	JP	C,PARAM_ERROR
	LD	A,(CLI_TOKEN_LEN)
	CP	5
	JP	NZ,PARAM_ERROR
	CALL	PARSE_HASH_HEX
	JP	C,PARAM_ERROR
	LD	A,B
	OR	C
	JP	Z,PARAM_ERROR
	LD	A,B
	CP	0x01
	JR	C,.COUNT_OK
	JP	NZ,PARAM_ERROR
	LD	A,C
	OR	A
	JP	NZ,PARAM_ERROR
.COUNT_OK
	LD	(CLI_COUNT),BC
	JP	.TOKEN_LOOP

.VERBOSE
	LD	A,(CLI_MODE)
	OR	A
	JP	NZ,PARAM_ERROR
	LD	A,SEEN_VERBOSE
	CALL	MARK_UNIQUE
	JP	C,PARAM_ERROR
	LD	A,1
	LD	(CLI_VERBOSE),A
	JP	.TOKEN_LOOP

.END_ARGS
	LD	A,(CLI_MODE)
	CP	MODE_PROBE
	JR	NZ,.SUCCESS
	LD	A,(CLI_SEEN)
	AND	SEEN_SLOT | SEEN_BASE | SEEN_COUNT
	CP	SEEN_SLOT | SEEN_BASE | SEEN_COUNT
	JR	NZ,PARAM_ERROR
	LD	HL,(CLI_BASE)
	LD	BC,(CLI_COUNT)
	ADD	HL,BC
	JR	C,PARAM_ERROR
	LD	DE,0x4000
	OR	A
	SBC	HL,DE
	JR	C,.SUCCESS
	JR	Z,.SUCCESS
	JR	PARAM_ERROR
.SUCCESS
	XOR	A
	RET

HELP_RESULT
	LD	A,EL3_CLI_HELP
	SCF
	RET

PARAM_ERROR
	LD	A,EL3_ERR_PARAMETER
	SCF
	RET

READER_INIT
	LD	HL,(CMDLINE_SOURCE)
	LD	A,(HL)
	INC	HL
	LD	(CLI_READER_PTR),HL
	LD	(CLI_READER_REMAIN),A
	RET

; NEXT_TOKEN
; Out: HL=start, CLI_TOKEN_LEN=len, CF=0; CF=1 at end. Bounded by DSS length.
NEXT_TOKEN
	LD	HL,(CLI_READER_PTR)
	LD	A,(CLI_READER_REMAIN)
	LD	B,A
.SKIP
	LD	A,B
	OR	A
	JR	Z,.NONE
	LD	A,(HL)
	CP	' '
	JR	Z,.SKIP_ONE
	CP	9
	JR	NZ,.START
.SKIP_ONE
	INC	HL
	DEC	B
	JR	.SKIP
.START
	PUSH	HL
	LD	C,0
.SCAN
	LD	A,B
	OR	A
	JR	Z,.DONE
	LD	A,(HL)
	CP	' '
	JR	Z,.DONE
	CP	9
	JR	Z,.DONE
	INC	HL
	INC	C
	DEC	B
	JR	.SCAN
.DONE
	LD	(CLI_READER_PTR),HL
	LD	A,B
	LD	(CLI_READER_REMAIN),A
	LD	A,C
	LD	(CLI_TOKEN_LEN),A
	POP	HL
	OR	A
	RET
.NONE
	LD	(CLI_READER_PTR),HL
	XOR	A
	LD	(CLI_READER_REMAIN),A
	SCF
	RET

MARK_UNIQUE
	LD	B,A
	LD	A,(CLI_SEEN)
	AND	B
	JR	NZ,.DUPLICATE
	LD	A,(CLI_SEEN)
	OR	B
	LD	(CLI_SEEN),A
	OR	A
	RET
.DUPLICATE
	SCF
	RET

TO_LOWER
	CP	'A'
	RET	C
	CP	'Z'+1
	RET	NC
	ADD	A,'a'-'A'
	RET

; IS_AUTO_TOKEN: CF=0 if current token equals AUTO case-insensitively.
IS_AUTO_TOKEN
	LD	A,(CLI_TOKEN_LEN)
	CP	4
	JR	NZ,.NO
	LD	DE,AUTO_TEXT
	LD	B,4
.LOOP
	LD	A,(HL)
	CALL	TO_LOWER
	LD	C,A
	LD	A,(DE)
	CP	C
	JR	NZ,.NO
	INC	HL
	INC	DE
	DJNZ	.LOOP
	OR	A
	RET
.NO
	SCF
	RET

; PARSE_HASH_HEX
; In: HL=token, CLI_TOKEN_LEN=4 or 5. Out: BC=value, CF status.
PARSE_HASH_HEX
	LD	A,(HL)
	CP	'#'
	JR	NZ,.BAD
	INC	HL
	LD	A,(CLI_TOKEN_LEN)
	DEC	A
	LD	B,A
	LD	DE,0
.DIGIT
	LD	A,(HL)
	CALL	HEX_NIBBLE
	JR	C,.BAD
	LD	C,A
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	LD	A,E
	OR	C
	LD	E,A
	INC	HL
	DJNZ	.DIGIT
	LD	B,D
	LD	C,E
	OR	A
	RET
.BAD
	SCF
	RET

HEX_NIBBLE
	CP	'0'
	JR	C,.BAD
	CP	'9'+1
	JR	C,.DEC
	CALL	TO_LOWER
	CP	'a'
	JR	C,.BAD
	CP	'f'+1
	JR	NC,.BAD
	SUB	'a'-10
	OR	A
	RET
.DEC
	SUB	'0'
	OR	A
	RET
.BAD
	SCF
	RET

AUTO_TEXT	DB "auto"

	ENDMODULE
	ENDIF
