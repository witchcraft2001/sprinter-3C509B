	LD	DE,NCV_NET
	CALL	COPY_Z
	LD	HL,DEFAULT_HW
	LD	DE,NCV_HW
	CALL	COPY_Z
	LD	HL,DEFAULT_IDPORT
	LD	DE,NCV_IDPORT
