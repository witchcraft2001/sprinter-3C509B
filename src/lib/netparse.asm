	OR	A
	JR	Z,.BAD
	LD	DE,NET_NETMASK
	CALL	PARSE_IPV4
	JR	C,.BAD
	LD	HL,NCV_GW
	LD	A,(HL)
	OR	A
	JR	Z,.GW_ZERO
	LD	DE,NET_GATEWAY
	CALL	PARSE_IPV4
	JR	C,.BAD
	JR	.OPTIONAL_IPS
.GW_ZERO
	LD	HL,0
	LD	(NET_GATEWAY),HL
	LD	(NET_GATEWAY+2),HL
.OPTIONAL_IPS
	LD	HL,NCV_DNS1
	CALL	PARSE_OPTIONAL_IP
	JR	C,.BAD
	LD	HL,NCV_DNS2
	CALL	PARSE_OPTIONAL_IP
