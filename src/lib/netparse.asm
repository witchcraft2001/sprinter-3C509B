VALIDATE
	LD	HL,(NETCFG_SEEN)
	LD	A,L
	AND	LOW (NC_SEEN_NET | NC_SEEN_IP)
	CP	LOW (NC_SEEN_NET | NC_SEEN_IP)
	JP	NZ,.BAD
	LD	HL,NCV_NET
	LD	DE,DEFAULT_NET
	CALL	STR_EQ_CI
	JP	NZ,.BAD
