; LOAD reads only <APPINFO home>\NET.CFG into the mapped Stage 7 TX region.
; Exact-capacity input is rejected as oversized. The handle closes on all paths.
LOAD
	PUSH	IX,IY
	LD	HL,NETCFG_PATH
	LD	B,APPINFO_EXE_HOMEDIR
	LD	C,DSS_APPINFO
	RST	DSS
	JR	C,.FILE_ERROR
	LD	HL,NETCFG_PATH
	CALL	APPEND_FILENAME
	JR	C,.FILE_ERROR
	LD	A,FM_READ
	LD	C,DSS_OPEN_FILE
	RST	DSS
	JR	C,.FILE_ERROR
	LD	(NETCFG_FILE_HANDLE),A
	LD	HL,STAGE7_TX_BUFFER
	LD	DE,STAGE7_TX_CAPACITY
	LD	C,DSS_READ_FILE
	RST	DSS
	JR	C,.READ_ERROR
	LD	(NETCFG_FILE_LENGTH),DE
	LD	A,(NETCFG_FILE_HANDLE)
	LD	C,DSS_CLOSE_FILE
	RST	DSS
	JR	C,.FILE_ERROR
	LD	HL,(NETCFG_FILE_LENGTH)
	LD	DE,STAGE7_TX_CAPACITY
	OR	A
	SBC	HL,DE
	JR	NC,.OVERSIZED
	LD	HL,STAGE7_TX_BUFFER
	LD	DE,(NETCFG_FILE_LENGTH)
	ADD	HL,DE
	LD	(HL),0
	LD	HL,STAGE7_TX_BUFFER
	LD	BC,(NETCFG_FILE_LENGTH)
	CALL	PARSE
	POP	IY,IX
	RET
.READ_ERROR
	LD	(NETPARSE_SAVED_ERROR),A
	LD	A,(NETCFG_FILE_HANDLE)
	LD	C,DSS_CLOSE_FILE
	RST	DSS
	LD	A,(NETPARSE_SAVED_ERROR)
.FILE_ERROR
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET
.OVERSIZED
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

APPEND_FILENAME
	LD	B,0			; bounded 256-byte APPINFO result scan
.SCAN
	LD	A,(HL)
	OR	A
	JR	Z,.END
	INC	HL
	DJNZ	.SCAN
	SCF
	RET
.END
	LD	A,L
	CP	LOW NETCFG_PATH
	JR	NZ,.HAVE_DIR
	LD	A,H
	CP	HIGH NETCFG_PATH
	JR	Z,.BAD
.HAVE_DIR
	DEC	HL
	LD	A,(HL)
	INC	HL
	CP	'\'
	JR	Z,.COPY
	CP	'/'
	JR	Z,.COPY
	LD	(HL),'\'
	INC	HL
.COPY
	LD	DE,CFG_FILENAME
	LD	B,8
.COPY_LOOP
	LD	A,(DE)
	LD	(HL),A
	INC	DE
	INC	HL
	DJNZ	.COPY_LOOP
	LD	HL,NETCFG_PATH
	OR	A
	RET
.BAD
	SCF
	RET

; PARSE operates over exactly BC bytes and supports LF, CRLF and CR. Unknown
; and duplicate keys increment NETCFG_WARNINGS; duplicate known keys use last.
PARSE
	PUSH	IX,IY
	LD	(NETPARSE_CURSOR),HL
	LD	(NETPARSE_REMAIN),BC
	CALL	DEFAULTS
.LINE
	LD	HL,(NETPARSE_REMAIN)
	LD	A,H
	OR	L
	JP	Z,.VALIDATE
	CALL	SKIP_EOL_SPACE
	LD	HL,(NETPARSE_REMAIN)
	LD	A,H
	OR	L
	JP	Z,.VALIDATE
	LD	HL,(NETPARSE_CURSOR)
	LD	A,(HL)
	CP	'#'
	JR	Z,.SKIP_LINE
	LD	(NETPARSE_KEY_START),HL
	XOR	A
	LD	(NETPARSE_KEY_LENGTH),A
.KEY
	CALL	GET_BYTE
	JR	C,.MALFORMED
	CP	'='
	JR	Z,.VALUE
	CP	13
	JR	Z,.MALFORMED
	CP	10
	JR	Z,.MALFORMED
	CP	' '
	JR	Z,.KEY_SPACE
	CP	9
	JR	Z,.KEY_SPACE
	CALL	UPPER_A
	LD	(HL),A			; GET_BYTE returned HL at consumed byte
	LD	A,(NETPARSE_KEY_LENGTH)
	INC	A
	LD	(NETPARSE_KEY_LENGTH),A
	CP	16
	JR	NC,.MALFORMED
	JR	.KEY
.KEY_SPACE
	CALL	SKIP_TO_EQUALS
	JR	C,.MALFORMED
.VALUE
	LD	HL,(NETPARSE_CURSOR)
	CALL	SKIP_INLINE_SPACE
	LD	(NETPARSE_VALUE_START),HL
	XOR	A
	LD	(NETPARSE_VALUE_LENGTH),A
.VALUE_SCAN
	LD	HL,(NETPARSE_REMAIN)
	LD	A,H
	OR	L
	JR	Z,.VALUE_END
	CALL	GET_BYTE
	CP	13
	JR	Z,.VALUE_END
	CP	10
	JR	Z,.VALUE_END
	LD	A,(NETPARSE_VALUE_LENGTH)
	INC	A
	LD	(NETPARSE_VALUE_LENGTH),A
	CP	64
	JR	NC,.MALFORMED
	JR	.VALUE_SCAN
.VALUE_END
	LD	HL,(NETPARSE_VALUE_START)
	LD	A,(NETPARSE_VALUE_LENGTH)
	LD	C,A
	CALL	TRIM_VALUE
	LD	(NETPARSE_VALUE_LENGTH),A
	CALL	DISPATCH_KEY
	JR	C,.MALFORMED
	JP	.LINE
.SKIP_LINE
	CALL	SKIP_TO_EOL
	JP	.LINE
.VALIDATE
	CALL	VALIDATE
	POP	IY,IX
	RET
.MALFORMED
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

DEFAULTS
	LD	HL,NETCFG_VALUES
	LD	BC,NCV_END-NETCFG_VALUES
	XOR	A
.CLEAR
	XOR	A
	LD	(HL),A
	INC	HL
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,.CLEAR
	LD	HL,DEFAULT_NET
	LD	DE,NCV_NET
	CALL	COPY_Z
	LD	HL,DEFAULT_HW
	LD	DE,NCV_HW
	CALL	COPY_Z
	LD	HL,DEFAULT_IDPORT
	LD	DE,NCV_IDPORT
	CALL	COPY_Z
	XOR	A
	LD	(NETCFG_WARNINGS),A
	LD	HL,0
	LD	(NETCFG_SEEN),HL
	LD	HL,NETDRV_CONFIG
	LD	BC,NETDRV_CONFIG_LENGTH
.CFG_CLEAR
	XOR	A
	LD	(HL),0
	INC	HL
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,.CFG_CLEAR
	LD	A,NETDRV_CONFIG_VERSION
	LD	(NETDRV_CONFIG+NETDRV_CFG_VERSION),A
	LD	A,NETDRV_CONFIG_LENGTH
	LD	(NETDRV_CONFIG+NETDRV_CFG_LENGTH),A
	LD	HL,EL3_IDPORT_DEFAULT
	LD	(NETDRV_CONFIG+NETDRV_CFG_IDPORT),HL
	RET

; GET_BYTE consumes one bounded byte, returning its address in HL and byte A.
GET_BYTE
	LD	BC,(NETPARSE_REMAIN)
	LD	A,B
	OR	C
	JR	Z,.EMPTY
	LD	HL,(NETPARSE_CURSOR)
	LD	A,(HL)
	INC	HL
	LD	(NETPARSE_CURSOR),HL
	DEC	BC
	LD	(NETPARSE_REMAIN),BC
	DEC	HL
	OR	A
	RET
.EMPTY
	SCF
	RET

SKIP_EOL_SPACE
.LOOP
	LD	BC,(NETPARSE_REMAIN)
	LD	A,B
	OR	C
	RET	Z
	LD	HL,(NETPARSE_CURSOR)
	LD	A,(HL)
	CP	13
	JR	Z,.ONE
	CP	10
	JR	Z,.ONE
	CP	' '
	JR	Z,.ONE
	CP	9
	RET	NZ
.ONE
	CALL	GET_BYTE
	JR	.LOOP

SKIP_INLINE_SPACE
.LOOP
	LD	A,(HL)
	CP	' '
	JR	Z,.ONE
	CP	9
	RET	NZ
.ONE
	INC	HL
	LD	(NETPARSE_CURSOR),HL
	LD	BC,(NETPARSE_REMAIN)
	DEC	BC
	LD	(NETPARSE_REMAIN),BC
	JR	.LOOP

SKIP_TO_EQUALS
.LOOP
	CALL	GET_BYTE
	RET	C
	CP	'='
	RET	Z
	CP	' '
	JR	Z,.LOOP
	CP	9
	JR	Z,.LOOP
	SCF
	RET

SKIP_TO_EOL
.LOOP
	CALL	GET_BYTE
	RET	C
	CP	13
	RET	Z
	CP	10
	RET	Z
	JR	.LOOP

; HL=start, C=raw length. Returns A=trimmed length and writes NUL terminator.
TRIM_VALUE
	LD	B,0
	ADD	HL,BC
.TRIM
	LD	A,C
	OR	A
	JR	Z,.DONE
	DEC	HL
	LD	A,(HL)
	CP	' '
	JR	Z,.REMOVE
	CP	9
	JR	NZ,.RESTORE
.REMOVE
	DEC	C
	JR	.TRIM
.RESTORE
	INC	HL
.DONE
	LD	(HL),0
	LD	A,C
	RET

DISPATCH_KEY
	LD	HL,KEY_TABLE
.NEXT
	LD	A,(HL)
	OR	A
	JR	Z,.UNKNOWN
	LD	(NETPARSE_MATCH_RECORD),HL
	PUSH	HL
	LD	DE,(NETPARSE_KEY_START)
	CALL	MATCH_NAME
	POP	HL
	JR	Z,.MATCH
	CALL	ADVANCE_RECORD
	JR	.NEXT
.MATCH
	CALL	ADVANCE_NAME
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	INC	HL
	LD	(NETPARSE_MATCH_BIT),DE
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	INC	HL
	LD	A,(HL)			; destination capacity
	LD	(NETPARSE_DESTINATION),DE
	LD	(NETPARSE_CAPACITY),A
	LD	DE,(NETPARSE_MATCH_BIT)
	CALL	MARK_SEEN
	LD	A,(NETPARSE_CAPACITY)
	LD	B,A
	LD	A,(NETPARSE_VALUE_LENGTH)
	CP	B
	JR	NC,.BAD
	LD	C,A
	LD	B,0
	LD	HL,(NETPARSE_VALUE_START)
	LD	DE,(NETPARSE_DESTINATION)
	LD	A,C
	OR	A
	JR	Z,.TERMINATE
	LDIR
.TERMINATE
	XOR	A
	LD	(DE),A
	RET
.UNKNOWN
	LD	A,(NETCFG_WARNINGS)
	INC	A
	LD	(NETCFG_WARNINGS),A
	OR	A
	RET
.BAD
	SCF
	RET

; MATCH_NAME compares ASCIIZ table name HL with key bytes DE/key length.
MATCH_NAME
	LD	A,(NETPARSE_KEY_LENGTH)
	LD	B,A
.LOOP
	LD	A,B
	OR	A
	JR	Z,.END
	LD	A,(HL)
	OR	A
	JR	Z,.NO
	LD	C,A
	LD	A,(DE)
	CP	C
	JR	NZ,.NO
	INC	HL
	INC	DE
	DJNZ	.LOOP
.END
	LD	A,(HL)
	OR	A
	RET
.NO
	OR	1
	RET

; Helpers for table records: name,0, bit word, destination word, capacity byte.
ADVANCE_NAME
.AN
	LD	A,(HL)
	INC	HL
	OR	A
	JR	NZ,.AN
	RET
ADVANCE_RECORD
	CALL	ADVANCE_NAME
	LD	DE,5
	ADD	HL,DE
	RET

MARK_SEEN
	; In DE=bit mask. Duplicate increments warning, then last value still wins.
	LD	HL,(NETCFG_SEEN)
	LD	A,L
	AND	E
	LD	C,A
	LD	A,H
	AND	D
	OR	C
	JR	Z,.NEW
	LD	A,(NETCFG_WARNINGS)
	INC	A
	LD	(NETCFG_WARNINGS),A
.NEW
	LD	A,L
	OR	E
	LD	L,A
	LD	A,H
	OR	D
	LD	H,A
	LD	(NETCFG_SEEN),HL
	RET

; Validate and normalize values into NETDRV_CONFIG plus IP source.
VALIDATE
	LD	HL,(NETCFG_SEEN)
	LD	A,L
	AND	LOW (NC_SEEN_NET | NC_SEEN_IP)
	CP	LOW (NC_SEEN_NET | NC_SEEN_IP)
	JP	NZ,.BAD
	LD	HL,NCV_NET
	LD	DE,DEFAULT_NET
	CALL	STR_EQ_CI
	JP	NZ,.BAD
	LD	HL,NCV_IDPORT
	CALL	PARSE_HASH_WORD
	JP	C,.BAD
	LD	A,H
	CP	1
	JP	NZ,.BAD
	LD	A,L
	AND	0x0F
	JP	NZ,.BAD
	LD	(NETDRV_CONFIG+NETDRV_CFG_IDPORT),HL
	LD	HL,NCV_HW
	LD	DE,DEFAULT_HW
	CALL	STR_EQ_CI
	JR	NZ,.EXPLICIT_HW
	XOR	A
	LD	(NETDRV_CONFIG+NETDRV_CFG_MODE),A
	JR	.MAC
.EXPLICIT_HW
	CALL	PARSE_HW
	JP	C,.BAD
.MAC
	LD	HL,NCV_MAC
	LD	A,(HL)
	OR	A
	JR	Z,.IP
	LD	DE,NETDRV_CONFIG+NETDRV_CFG_MAC
	CALL	PARSE_MAC
	JR	C,.BAD
	LD	A,NETDRV_MAC_OVERRIDE
	LD	(NETDRV_CONFIG+NETDRV_CFG_MAC_FLAGS),A
.IP
	LD	HL,NCV_IP
	LD	DE,VALUE_DHCP
	CALL	STR_EQ_CI
	JR	NZ,.STATIC
	LD	HL,VALUE_DHCP
	LD	DE,NCV_IP_SRC
	CALL	COPY_Z
	XOR	A
	LD	(NCV_IP),A
	JR	.VALIDATE_TZ
.STATIC
	LD	DE,NET_LOCAL_IP
	CALL	PARSE_IPV4
	JR	C,.BAD
	LD	HL,NCV_MASK
	LD	A,(HL)
	OR	A
	JR	Z,.BAD
	LD	DE,NET_NETMASK
	CALL	PARSE_IPV4
	JR	C,.BAD
	LD	HL,NCV_GW
	LD	A,(HL)
	OR	A
	JR	Z,.GW_ZERO
	LD	DE,NET_GATEWAY
	CALL	PARSE_IPV4
	JR	C,.BAD
	JR	.OPTIONAL_IPS
.GW_ZERO
	LD	HL,0
	LD	(NET_GATEWAY),HL
	LD	(NET_GATEWAY+2),HL
.OPTIONAL_IPS
	LD	HL,NCV_DNS1
	CALL	PARSE_OPTIONAL_IP
	JR	C,.BAD
	LD	HL,NCV_DNS2
	CALL	PARSE_OPTIONAL_IP
	JR	C,.BAD
	LD	HL,VALUE_STATIC
	LD	DE,NCV_IP_SRC
	CALL	COPY_Z
	; NETCFG and every environment consumer share the same quarter-hour TZ
	; grammar. The parsed offset is intentionally not persisted as hidden state.
.VALIDATE_TZ
	LD	HL,NCV_TZ
	CALL	PARSE_TZ
	JR	C,.BAD
	XOR	A
	RET
.BAD
	LD	A,NETDRV_ERR_CONFIG
	SCF
	RET

PARSE_OPTIONAL_IP
	LD	A,(HL)
	OR	A
	RET	Z
	LD	DE,NETCFG_SCRATCH
	JP	PARSE_IPV4

; PARSE_TZ
; In: HL=ASCIIZ timezone in [+|-]H, HH, H:MM or HH:MM form. Empty means UTC.
; Out: DE=signed offset minutes, A=0/CF=0; CF=1 on syntax/range error.
; Minutes are restricted to 00/15/30/45 and the range is -12:00..+14:00.
; Preserves IX/IY.
PARSE_TZ
	PUSH	IX,IY
	; The longest accepted spelling is six bytes (for example +12:45).
	; Bound the ASCIIZ scan before parsing so hostile API input cannot enter
	; the ISA window or wrap around memory.
	PUSH	HL
	LD	B,0
.TZ_BOUND
	LD	A,H
	CP	0xC0
	JR	NC,.TZ_BOUND_BAD
	LD	A,(HL)
	OR	A
	JR	Z,.TZ_BOUND_OK
	INC	HL
	INC	B
	LD	A,B
	CP	7
	JR	C,.TZ_BOUND
.TZ_BOUND_BAD
	POP	HL
	JP	.TZ_BAD
.TZ_BOUND_OK
	POP	HL
	XOR	A
	LD	(NETPARSE_TZ_NEGATIVE),A
	LD	(NETPARSE_TZ_MINUTES),A
	LD	A,(HL)
	OR	A
	JP	Z,.TZ_ZERO
	CP	'+'
	JR	Z,.TZ_SIGN_DONE
	CP	'-'
	JR	NZ,.TZ_HOUR
	LD	A,1
	LD	(NETPARSE_TZ_NEGATIVE),A
.TZ_SIGN_DONE
	INC	HL
.TZ_HOUR
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	LD	C,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JR	C,.TZ_AFTER_HOUR
	CP	'9'+1
	JR	NC,.TZ_AFTER_HOUR
	SUB	'0'
	LD	B,A
	LD	A,C
	ADD	A,A
	LD	C,A
	ADD	A,A
	ADD	A,A
	ADD	A,C
	ADD	A,B
	LD	C,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JR	C,.TZ_AFTER_HOUR
	CP	'9'+1
	JP	C,.TZ_BAD		; a third hour digit is invalid
.TZ_AFTER_HOUR
	OR	A
	JR	Z,.TZ_RANGE
	CP	':'
	JP	NZ,.TZ_BAD
	INC	HL
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	ADD	A,A
	LD	B,A
	ADD	A,A
	ADD	A,A
	ADD	A,B			; tens * 10
	LD	B,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	ADD	A,B
	LD	(NETPARSE_TZ_MINUTES),A
	INC	HL
	LD	A,(HL)
	OR	A
	JP	NZ,.TZ_BAD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JR	Z,.TZ_RANGE
	CP	15
	JR	Z,.TZ_RANGE
	CP	30
	JR	Z,.TZ_RANGE
	CP	45
	JP	NZ,.TZ_BAD
.TZ_RANGE
	LD	A,(NETPARSE_TZ_NEGATIVE)
	OR	A
	JR	NZ,.TZ_NEG_RANGE
	LD	A,C
	CP	15
	JP	NC,.TZ_BAD
	CP	14
	JR	NZ,.TZ_BUILD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JP	NZ,.TZ_BAD
	JR	.TZ_BUILD
.TZ_NEG_RANGE
	LD	A,C
	CP	13
	JP	NC,.TZ_BAD
	CP	12
	JR	NZ,.TZ_BUILD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JP	NZ,.TZ_BAD
.TZ_BUILD
	LD	DE,0
	LD	A,C
	OR	A
	JR	Z,.TZ_ADD_MINUTES
	LD	B,A
.TZ_HOUR_LOOP
	LD	HL,60
	ADD	HL,DE
	EX	DE,HL
	DJNZ	.TZ_HOUR_LOOP
.TZ_ADD_MINUTES
	LD	A,(NETPARSE_TZ_MINUTES)
	LD	L,A
	LD	H,0
	ADD	HL,DE
	EX	DE,HL
	LD	A,(NETPARSE_TZ_NEGATIVE)
	OR	A
	JR	Z,.TZ_OK
	LD	HL,0
	OR	A
	SBC	HL,DE
	EX	DE,HL
.TZ_OK
	XOR	A
	POP	IY,IX
	RET
.TZ_ZERO
	LD	DE,0
	JR	.TZ_OK
.TZ_BAD
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

; PARSE_U32
; In: HL=ASCIIZ unsigned decimal, DE=four-byte little-endian destination.
; Out: A=0/CF=0 or configuration error/CF=1. Exact 0..4294967295, bounded to
; ten digits; preserves IX/IY.
PARSE_U32
	PUSH	IX,IY
	LD	(NETPARSE_U32_DEST),DE
	PUSH	HL
	LD	B,0
.PU_LENGTH
	LD	A,H
	CP	0xC0
	JR	NC,.PU_BAD_POP
	LD	A,(HL)
	OR	A
	JR	Z,.PU_LENGTH_DONE
	INC	HL
	INC	B
	LD	A,B
	CP	11
	JR	C,.PU_LENGTH
.PU_BAD_POP
	POP	HL
	JR	.PU_BAD
.PU_LENGTH_DONE
	POP	HL
	LD	A,B
	OR	A
	JR	Z,.PU_BAD
	LD	(NETPARSE_U32_REMAIN),A
	XOR	A
	LD	(NETPARSE_U32+0),A
	LD	(NETPARSE_U32+1),A
	LD	(NETPARSE_U32+2),A
	LD	(NETPARSE_U32+3),A
.PU_LOOP
	LD	A,(HL)
	CP	'0'
	JR	C,.PU_BAD
	CP	'9'+1
	JR	NC,.PU_BAD
	SUB	'0'
	LD	(NETPARSE_U32_DIGIT),A
	PUSH	HL
	CALL	U32_TIMES10
	POP	HL
	JR	C,.PU_BAD
	LD	A,(NETPARSE_U32_DIGIT)
	PUSH	HL
	LD	HL,NETPARSE_U32
	ADD	A,(HL)
	POP	HL
	LD	(NETPARSE_U32+0),A
	JR	NC,.PU_NEXT
	LD	A,(NETPARSE_U32+1)
	INC	A
	LD	(NETPARSE_U32+1),A
	JR	NZ,.PU_NEXT
	LD	A,(NETPARSE_U32+2)
	INC	A
	LD	(NETPARSE_U32+2),A
	JR	NZ,.PU_NEXT
	LD	A,(NETPARSE_U32+3)
	INC	A
	LD	(NETPARSE_U32+3),A
	JR	Z,.PU_BAD
.PU_NEXT
	INC	HL
	LD	A,(NETPARSE_U32_REMAIN)
	DEC	A
	LD	(NETPARSE_U32_REMAIN),A
	JR	NZ,.PU_LOOP
	LD	HL,NETPARSE_U32
	LD	DE,(NETPARSE_U32_DEST)
	LD	BC,4
	LDIR
	XOR	A
	POP	IY,IX
	RET
.PU_BAD
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

U32_TIMES10
	LD	HL,NETPARSE_U32
	LD	DE,NETPARSE_U32_COPY
	LD	BC,4
	LDIR
	LD	B,3
.UT_SHIFT8
	LD	HL,NETPARSE_U32
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C
	DJNZ	.UT_SHIFT8
	LD	HL,NETPARSE_U32_COPY
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C
	LD	HL,NETPARSE_U32
	LD	DE,NETPARSE_U32_COPY
	LD	B,4
	OR	A
.UT_ADD
	LD	A,(DE)
	ADC	A,(HL)
	LD	(HL),A
	INC	HL
	INC	DE
	DJNZ	.UT_ADD
	RET

PARSE_HW
	LD	A,(HL)
	CP	'0'
	JR	Z,.SLOT0
	CP	'1'
	JR	NZ,.BAD
	LD	A,1
	JR	.SLOT
.SLOT0
	XOR	A
.SLOT
	LD	(NETDRV_CONFIG+NETDRV_CFG_SLOT),A
	INC	HL
	LD	A,(HL)
	CP	'/'
	JR	NZ,.BAD
	INC	HL
	CALL	PARSE_HASH_WORD
	JR	C,.BAD
	PUSH	HL
	CALL	@EL3ALG.BASE_ENCODE
	POP	HL
