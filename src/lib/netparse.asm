; PARSE_TZ
; In: HL=ASCIIZ timezone in [+|-]H, HH, H:MM or HH:MM form. Empty means UTC.
; Out: DE=signed offset minutes, A=0/CF=0; CF=1 on syntax/range error.
; Minutes are restricted to 00/15/30/45 and the range is -12:00..+14:00.
; Preserves IX/IY.
PARSE_TZ
	PUSH	IX,IY
	; The longest accepted spelling is six bytes (for example +12:45).
	; Bound the ASCIIZ scan before parsing so hostile API input cannot enter
	; the ISA window or wrap around memory.
	PUSH	HL
	LD	B,0
.TZ_BOUND
	LD	A,H
	CP	0xC0
	JR	NC,.TZ_BOUND_BAD
	LD	A,(HL)
	OR	A
	JR	Z,.TZ_BOUND_OK
	INC	HL
	INC	B
	LD	A,B
	CP	7
	JR	C,.TZ_BOUND
.TZ_BOUND_BAD
	POP	HL
	JP	.TZ_BAD
.TZ_BOUND_OK
	POP	HL
	XOR	A
	LD	(NETPARSE_TZ_NEGATIVE),A
	LD	(NETPARSE_TZ_MINUTES),A
	LD	A,(HL)
	OR	A
	JP	Z,.TZ_ZERO
	CP	'+'
	JR	Z,.TZ_SIGN_DONE
	CP	'-'
	JR	NZ,.TZ_HOUR
	LD	A,1
	LD	(NETPARSE_TZ_NEGATIVE),A
.TZ_SIGN_DONE
	INC	HL
.TZ_HOUR
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	LD	C,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JR	C,.TZ_AFTER_HOUR
	CP	'9'+1
	JR	NC,.TZ_AFTER_HOUR
	SUB	'0'
	LD	B,A
	LD	A,C
	ADD	A,A
	LD	C,A
	ADD	A,A
	ADD	A,A
	ADD	A,C
	ADD	A,B
	LD	C,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JR	C,.TZ_AFTER_HOUR
	CP	'9'+1
	JP	C,.TZ_BAD		; a third hour digit is invalid
.TZ_AFTER_HOUR
	OR	A
	JR	Z,.TZ_RANGE
	CP	':'
	JP	NZ,.TZ_BAD
	INC	HL
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	ADD	A,A
	LD	B,A
	ADD	A,A
	ADD	A,A
	ADD	A,B			; tens * 10
	LD	B,A
	INC	HL
	LD	A,(HL)
	CP	'0'
	JP	C,.TZ_BAD
	CP	'9'+1
	JP	NC,.TZ_BAD
	SUB	'0'
	ADD	A,B
	LD	(NETPARSE_TZ_MINUTES),A
	INC	HL
	LD	A,(HL)
	OR	A
	JP	NZ,.TZ_BAD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JR	Z,.TZ_RANGE
	CP	15
	JR	Z,.TZ_RANGE
	CP	30
	JR	Z,.TZ_RANGE
	CP	45
	JP	NZ,.TZ_BAD
.TZ_RANGE
	LD	A,(NETPARSE_TZ_NEGATIVE)
	OR	A
	JR	NZ,.TZ_NEG_RANGE
	LD	A,C
	CP	15
	JP	NC,.TZ_BAD
	CP	14
	JR	NZ,.TZ_BUILD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JP	NZ,.TZ_BAD
	JR	.TZ_BUILD
.TZ_NEG_RANGE
	LD	A,C
	CP	13
	JP	NC,.TZ_BAD
	CP	12
	JR	NZ,.TZ_BUILD
	LD	A,(NETPARSE_TZ_MINUTES)
	OR	A
	JP	NZ,.TZ_BAD
.TZ_BUILD
	LD	DE,0
	LD	A,C
	OR	A
	JR	Z,.TZ_ADD_MINUTES
	LD	B,A
.TZ_HOUR_LOOP
	LD	HL,60
	ADD	HL,DE
	EX	DE,HL
	DJNZ	.TZ_HOUR_LOOP
.TZ_ADD_MINUTES
	LD	A,(NETPARSE_TZ_MINUTES)
	LD	L,A
	LD	H,0
	ADD	HL,DE
	EX	DE,HL
	LD	A,(NETPARSE_TZ_NEGATIVE)
	OR	A
	JR	Z,.TZ_OK
	LD	HL,0
	OR	A
	SBC	HL,DE
	EX	DE,HL
.TZ_OK
	XOR	A
	POP	IY,IX
	RET
.TZ_ZERO
	LD	DE,0
	JR	.TZ_OK
.TZ_BAD
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

; PARSE_U32
; In: HL=ASCIIZ unsigned decimal, DE=four-byte little-endian destination.
; Out: A=0/CF=0 or configuration error/CF=1. Exact 0..4294967295, bounded to
; ten digits; preserves IX/IY.
PARSE_U32
	PUSH	IX,IY
	LD	(NETPARSE_U32_DEST),DE
	PUSH	HL
	LD	B,0
.PU_LENGTH
	LD	A,H
	CP	0xC0
	JR	NC,.PU_BAD_POP
	LD	A,(HL)
	OR	A
	JR	Z,.PU_LENGTH_DONE
	INC	HL
	INC	B
	LD	A,B
	CP	11
	JR	C,.PU_LENGTH
.PU_BAD_POP
	POP	HL
	JR	.PU_BAD
.PU_LENGTH_DONE
	POP	HL
	LD	A,B
	OR	A
	JR	Z,.PU_BAD
	LD	(NETPARSE_U32_REMAIN),A
	XOR	A
	LD	(NETPARSE_U32+0),A
	LD	(NETPARSE_U32+1),A
	LD	(NETPARSE_U32+2),A
	LD	(NETPARSE_U32+3),A
.PU_LOOP
	LD	A,(HL)
	CP	'0'
	JR	C,.PU_BAD
	CP	'9'+1
	JR	NC,.PU_BAD
	SUB	'0'
	LD	(NETPARSE_U32_DIGIT),A
	PUSH	HL
	CALL	U32_TIMES10
	POP	HL
	JR	C,.PU_BAD
	LD	A,(NETPARSE_U32_DIGIT)
	PUSH	HL
	LD	HL,NETPARSE_U32
	ADD	A,(HL)
	POP	HL
	LD	(NETPARSE_U32+0),A
	JR	NC,.PU_NEXT
	LD	A,(NETPARSE_U32+1)
	INC	A
	LD	(NETPARSE_U32+1),A
	JR	NZ,.PU_NEXT
	LD	A,(NETPARSE_U32+2)
	INC	A
	LD	(NETPARSE_U32+2),A
	JR	NZ,.PU_NEXT
	LD	A,(NETPARSE_U32+3)
	INC	A
	LD	(NETPARSE_U32+3),A
	JR	Z,.PU_BAD
.PU_NEXT
	INC	HL
	LD	A,(NETPARSE_U32_REMAIN)
	DEC	A
	LD	(NETPARSE_U32_REMAIN),A
	JR	NZ,.PU_LOOP
	LD	HL,NETPARSE_U32
	LD	DE,(NETPARSE_U32_DEST)
	LD	BC,4
	LDIR
	XOR	A
	POP	IY,IX
	RET
.PU_BAD
	LD	A,NETDRV_ERR_CONFIG
	SCF
	POP	IY,IX
	RET

U32_TIMES10
	LD	HL,NETPARSE_U32
	LD	DE,NETPARSE_U32_COPY
	LD	BC,4
	LDIR
	LD	B,3
.UT_SHIFT8
	LD	HL,NETPARSE_U32
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C
	DJNZ	.UT_SHIFT8
	LD	HL,NETPARSE_U32_COPY
	SLA	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	INC	HL
	RL	(HL)
	RET	C
	LD	HL,NETPARSE_U32
	LD	DE,NETPARSE_U32_COPY
	LD	B,4
	OR	A
.UT_ADD
	LD	A,(DE)
	ADC	A,(HL)
	LD	(HL),A
	INC	HL
	INC	DE
	DJNZ	.UT_ADD
	RET

PARSE_HW
	LD	A,(HL)
	CP	'0'
	JR	Z,.SLOT0
	CP	'1'
	JR	NZ,.BAD
	LD	A,1
	JR	.SLOT
.SLOT0
	XOR	A
.SLOT
	LD	(NETDRV_CONFIG+NETDRV_CFG_SLOT),A
	INC	HL
	LD	A,(HL)
	CP	'/'
	JR	NZ,.BAD
	INC	HL
	CALL	PARSE_HASH_WORD
	JR	C,.BAD
	PUSH	HL
	CALL	@EL3ALG.BASE_ENCODE
	POP	HL
	JR	C,.BAD
	LD	(NETDRV_CONFIG+NETDRV_CFG_BASE),HL
	LD	A,NETDRV_MODE_EXPLICIT
	LD	(NETDRV_CONFIG+NETDRV_CFG_MODE),A
	XOR	A
	RET
.BAD
	SCF
	RET

; #HHH/#HHHH, exact NUL termination.
PARSE_HASH_WORD
	LD	A,(HL)
	CP	'#'
	JR	NZ,.BAD
	INC	HL
	LD	DE,0
	LD	B,0
.HEX
	LD	A,(HL)
	OR	A
	JR	Z,.DONE
	CALL	HEX_NIBBLE
	JR	C,.BAD
	LD	C,A
	LD	A,D
	AND	0xF0
	JR	NZ,.BAD
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	SLA	E
	RL	D
	LD	A,E
	OR	C
	LD	E,A
	INC	HL
	INC	B
	LD	A,B
	CP	5
	JR	C,.HEX
.BAD
	SCF
	RET
.DONE
	LD	A,B
	OR	A
	JR	Z,.BAD
	EX	DE,HL
	OR	A
	RET

HEX_NIBBLE
	CP	'0'
	JR	C,.BAD
	CP	'9'+1
	JR	C,.DIGIT
	CALL	UPPER_A
	CP	'A'
	JR	C,.BAD
	CP	'F'+1
	JR	NC,.BAD
	SUB	'A'-10
	OR	A
	RET
.DIGIT
	SUB	'0'
	OR	A
	RET
.BAD
	SCF
	RET

; Exact six-byte colon MAC; rejects multicast, all-zero and broadcast.
PARSE_MAC
	LD	B,6
	LD	C,0
.BYTE
	LD	A,(HL)
	CALL	HEX_NIBBLE
	RET	C
	RLCA
	RLCA
	RLCA
	RLCA
	LD	C,A
	INC	HL
	LD	A,(HL)
	CALL	HEX_NIBBLE
	RET	C
	OR	C
	LD	(DE),A
	INC	DE
	INC	HL
	DEC	B
	JR	Z,.END
	LD	A,(HL)
	CP	':'
	JR	NZ,.BAD
	INC	HL
	JR	.BYTE
.END
	LD	A,(HL)
	OR	A
	JR	NZ,.BAD
	LD	A,(NETDRV_CONFIG+NETDRV_CFG_MAC)
	AND	1
	JR	NZ,.BAD
	LD	HL,NETDRV_CONFIG+NETDRV_CFG_MAC
	LD	B,6
	XOR	A
.NONZERO
	OR	(HL)
	INC	HL
	DJNZ	.NONZERO
	JR	Z,.BAD
	XOR	A
	RET
.BAD
	SCF
	RET

; Dotted decimal parser with exact termination. In HL=text, DE=4 bytes.
PARSE_IPV4
	LD	B,4
.OCTET
	LD	C,0
	LD	A,(HL)
	CP	'0'
	JR	C,.BAD
	CP	'9'+1
	JR	NC,.BAD
	LD	A,0
	LD	(NETPARSE_DIGITS),A
.DIGIT
	LD	A,(HL)
	CP	'0'
	JR	C,.END_OCTET
	CP	'9'+1
	JR	NC,.END_OCTET
	SUB	'0'
	LD	(NETPARSE_DIGIT),A
	LD	A,C
	CP	26
	JR	NC,.BAD
	ADD	A,A
	LD	(NETPARSE_TIMES2),A
	ADD	A,A
	ADD	A,A
	LD	C,A			; old*8
	LD	A,(NETPARSE_TIMES2)
	ADD	A,C			; old*10
	LD	C,A
	LD	A,(NETPARSE_DIGIT)
	ADD	A,C
	JR	C,.BAD
	LD	C,A
	INC	HL
	LD	A,(NETPARSE_DIGITS)
	INC	A
	LD	(NETPARSE_DIGITS),A
	CP	4
	JR	NC,.BAD
	JR	.DIGIT
.END_OCTET
	LD	A,C
	LD	(DE),A
	INC	DE
	DEC	B
	JR	Z,.LAST
	LD	A,(HL)
	CP	'.'
	JR	NZ,.BAD
	INC	HL
	JR	.OCTET
.LAST
	LD	A,(HL)
	OR	A
	JR	NZ,.BAD
	XOR	A
	RET
.BAD
	SCF
	RET

STR_EQ_CI
.LOOP
	LD	A,(HL)
	CALL	UPPER_A
	LD	C,A
	LD	A,(DE)
	CALL	UPPER_A
	CP	C
	RET	NZ
	OR	A
	RET	Z
	INC	HL
	INC	DE
	JR	.LOOP

UPPER_A
	CP	'a'
	RET	C
	CP	'z'+1
	RET	NC
	SUB	'a'-'A'
	RET

COPY_Z
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	OR	A
	JR	NZ,COPY_Z
	RET

